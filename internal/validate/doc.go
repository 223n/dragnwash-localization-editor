// Package validate は、公開ずみの Translations/<ロケール>/strings.csv が
// 公開してよい形をしているかを検査する。tools/check-translations.py の移植で、
// 元実装は CI がすべてのPull Requestで走らせている。
//
// 基準は上流の dev ブランチの版。003ed1e で移植したあと、
// f816618（空白だけの行、CSV として読めないとき）、c8fda90（コメントの判定）、
// cc01bfc（textures/）、912f519（credits.txt）に追いついている。
//
// 翻訳者の Pull Request は、これまでどおりフォークから main へ出す（上流 130d57e。
// dev はメンテナーの作業をためる場所）。そのため Pull Request の CI は main の
// check-translations.py で走る。main と dev の差は 912f519 の credits.txt の検査
// だけ。上流はこれまで dev をまとめて main へ入れてきた（56420df、#44）ので、次の
// リリースでも main に入る見込みで、ここではその版に先に合わせた。
// 結果として、版の差の分（credits.txt の状態語）は main の CI より厳しい。main の
// CI が通す credits.txt を、ここでは問題として報告することがある。ほかに、写さな
// かった上流の不具合（下の「元実装と意図的に変えたところ」）にあたる入力でも、
// ここだけが問題を報告する。
//
// このパッケージが守りたいものは2つある。
//
//   - 公開ファイルが機械で読める形を保つこと（ヘッダー、キーの形、重複、空の訳）。
//     ロケールごとの credits.txt の状態語と、textures/ の絵とその出典も見る。
//   - 英語原文が公開リポジトリに漏れないこと。原文は作品そのものなので、
//     source_en 列のあるファイルや Translations/_discovered/ の作業コピーが
//     コミットされていたら止める。
//
// 2つめの目的から、報告メッセージには key の値も原文も入れない。
// 元実装にも「on a public repository the report is visible, and a plain-text key
// is the game's script」というコメントがある。CIのログは誰でも読めるため、
// 「何行目がどう悪いか」までは書くが「その行に何が書いてあるか」は書かない。
// [Problem] が値を持たないのはそのため。
//
// # 検査の入口
//
//   - [CheckFile] はバイト列1つ分を検査する。ファイルを開かないので、
//     編集中のバッファをそのまま渡せる。
//   - [CheckTree] はリポジトリルートを受け取り、Translations 配下を丸ごと歩く。
//     元実装の main に対応する。
//
// # 読み方は internal/csvfile に任せる
//
// コメントの判定（引用符の偶奇を行をまたいで持ち回る）、完全な空行の捨て方、
// 報告用の物理行番号の対応付けは [csvfile.ReadPythonRecords] が持っている。
// Go の encoding/csv では再現できない（引用符で囲まないフィールド中の裸の '"'
// でパースが止まり、以降の行がまるごと無検査になる）ため、そちらは使わない。
// 詳しくは internal/csvfile のパッケージコメントを参照。
//
// # 元実装と意図的に変えたところ
//
//   - 正規表現の末尾 '$' の扱い。Python の '$' は末尾の改行1個の手前にも当たるため、
//     元実装では "UI\n" が識別子として通る。ここでは通さない（[looksLikeIdentifier]）。
//   - コメント行はパーサーに渡さない。上流は渡してから捨てるので、引用符を
//     開いたままのコメント行があると後ろの行が検査から漏れる。
//   - 行は "\r\n" / "\n" / "\r" だけで割る。上流の comment_lines は
//     str.splitlines() で数えるので、値に U+2028 などがあると行番号がずれて
//     誤報や見逃しが起きる。
//   - 例外で落ちる経路を落ちないようにした。Translations が無い・ファイルが読めない・
//     textures/credits.csv が CSV として読めないときは [CheckTree] がエラーを返す。
//     不正なUTF-8は元実装なら異常終了するが、ここでは検査を続ける。
//   - 出力は常にUTF-8。元実装は Windows のロケール依存で、非ASCIIを含む
//     メッセージを出そうとすると UnicodeEncodeError で落ちうる。
//
// 上の2つめと3つめは上流の不具合を写さないためで、その入力に限って判定が割れる。
// 前者では上流が見逃す問題をここだけが報告し、後者では上流だけが誤報や見逃しを起こす
// （どちらも internal/validate の upstream_test.go に入力を固定してある）。
// それ以外は「元実装が問題なしと言うものを問題ありにしない」方向に倒してある。
// 上流 dev の16ロケールに対しては、元実装と同じく問題0件になる。
