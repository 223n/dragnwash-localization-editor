// Package gamedir は、ゲームに入っているプラグインのフォルダーを探す。
//
// # なぜ要るか
//
// 翻訳者は2つのフォルダーを持っている。コミットする翻訳リポジトリと、ゲームが
// 読み書きするプラグインのフォルダーである。原文（英語の台本）が入った作業コピーは
// 後者にしかない。リポジトリ側の Translations/_discovered は .gitignore で
// 外してあり、ふつうは存在しない。作業コピーを見つけられないと、画面の原文の欄は
// 空のままで、「未翻訳」も判定できない。
//
// # 何を目印にするか
//
// 探すのは「Translations/_discovered を持つフォルダー」1点だけである。ゲームの
// フォルダー名もプラグインのフォルダー名も、利用者が変えていることがある。
// 名前で当てにいくと、変えた人だけが見つけてもらえない。
//
// 決め打ちにしてよいのは steamapps/common と BepInEx/plugins の2つである。
// どちらも Steam と BepInEx が決める並びで、利用者が選ぶ名前ではない。
// その2つの間（ゲームのフォルダー名）と下（プラグインのフォルダー名）は、
// どちらもワイルドカードとして扱う。
//
// # 候補が複数あったら選ばない
//
// [Resolve] は候補が2つ以上あるとき [AmbiguousError] を返し、どれも使わない。
// ライブラリを2つ持っていて両方にゲームが入っている、以前の版を別名で残して
// ある、といった状態がありうる。片方を勝手に選ぶと、翻訳者は自分がどちらの
// ファイルを直しているのか分からないまま作業することになる。
//
// # このパッケージがしないこと
//
// ファイルを書かない。読むのは、フォルダーが在るかどうかと
// steamapps/libraryfolders.vdf の中身だけである。作業コピーの中身（原文）は
// 開かない。見つけた場所を覚えることもしない。
