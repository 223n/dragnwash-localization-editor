// Package diff は、公開ファイル（Translations/<ロケール>/strings.csv）と
// 再生順（data/script_order.csv）と作業コピー（Translations/_discovered/
// <ロケール>.working.csv）を突き合わせ、翻訳者が次にやることと、確かめたほうが
// よい行を並べる。
//
// このパッケージの目的は「見つけること」ではなく「誤検出を出さないこと」にある。
// 素朴に「再生順に無い公開キー＝孤児」と判定すると、実データでは13ロケールの
// それぞれで110件、合わせて1430件の誤検出になる。その110件は section 列が 'UI' の
// UI 文言で、ゲームの画面にしか存在しない正常な行だからである（事前調査レポート
// 3.2 が名指しで警告している構図）。毎日走らせる道具が毎日1430件の嘘をつけば、
// その道具は使われなくなる。
//
// そこで「再生順に無い公開ハッシュキー」を、公開ファイルの中に残っている証拠だけで
// 3つに割る。
//
//   - section 列が 'UI' でない  → [CatVanished]（台本から消えた行・要確認）
//     publish は再生順に置けなかった行の section を必ず 'UI' に書き換えるので、
//     'UI' でない値が残っているのは「前回 publish した時点では再生順に置けていた」
//     という記録になる。ファイルの中に残る唯一の時間差の証拠。
//   - section が 'UI' で、speaker が 'UI' でも空でもない → [CatScriptGap]（参考）
//     publish も作業コピー生成も UI 文言の speaker には 'UI' か空しか書かないので、
//     話者名が残っている行は「かつて台詞として記録された」履歴を持つ。実データでは
//     13ロケールとも17件（Ryan 8 / Conrad 9）で、git 履歴の script_order.csv 全4版を
//     調べてもこの17件のキーは一度も載っていない。つまり消えたのではなく最初から
//     載っていない。
//   - 残り → [CatUnknownOrigin]（参考・既定では件数だけ）
//     公開ファイルだけでは UI 文言と孤児を見分けられない。UI 文言の収集は
//     「今ロードされているシーンの分だけ」なので、ゲーム側に無いことの証明は
//     そもそも取れない。
//
// section 列と node 列と order 列は同じ1ビットの言い換えでしかない（publish の
// appendLeftovers が3つを同時に書く）。実データで4集合（再生順に無い公開キー /
// section='UI' / node が空 / order が空）が完全に一致することは実測済みで、
// どれを見るかは好みの問題として、定数が既にある section に寄せた。
//
// 引き継ぎ候補:
//
// ゲームが更新されて英文が1文字でも変わると、その行のキーは別の値になる。公開CSVに
// 英文は入っていないので、旧キーの訳をどの新キーへ移せばよいかは、公開ファイルを
// 見ただけでは分からない。[CatCarryover] はその見当を示すが、訳には一切触れない。
//
// 手がかりにするのは data/script_order.csv の旧版（[carryoverCandidates]）。
// このファイルは git 管理下にあるので、1つ前の版を [GitOldOrder] で取り出し、
// 新旧を台詞ID (line_id) で突き合わせる。line_id は Yarn が台詞に振る識別子で、
// 英文が直されても変わらない。同じ line_id の行で key だけが変わっていれば、
// それは「その台詞の原文が書き換わった」という記録そのものになる。
//
//   - 旧キーがいまの再生順のどこにも無い       → [CarryMoved]（旧行はもう要らない）
//   - 旧キーがいまの再生順の別の行で生きている → [CarryCopied]（旧行の訳は残す）
//
// 公開ファイルと今の再生順だけで済ませる方式（ノードごとにキー列を最長共通部分列で
// 揃える）は捨てた。原理的に潰せない誤検出があったため。Translations/ignore.txt で
// 記録の対象外になっているキーは「どのロケールにも訳が無い」まま再生順に居座る。
// 「本当に新しく現れたキー」も公開CSVからは同じ姿に見えるので、公開ファイルだけでは
// 区別できない。全1839行を1行ずつ削って試すと、その32件のうち6行で誤った候補が出た。
// 旧版の再生順を見れば、前からあったのか今回現れたのかが直接分かる。
//
// 2026-09-14 のゲーム更新（英文の誤記修正で25行のキーが変わった）を再現すると、
// 候補は24件（移動23・複製1）で、誤りは0件だった
// （TestRealDataGameUpdateCarryover）。旧版と新版はどちらも1839行で line_id の
// 集合が完全に一致し、新しく現れた24キーは全部が再キー付け、本当に新しく足された
// 台詞は0件だった。
//
// 表示では、その区別を行の先頭に置き、「複製」を一覧の先頭へ回す
// （[carryCopiedFirst]）。取り違えると、いまも再生されている行の訳を消させる
// ことになるのに、実データでは24件中1件しかなく、キー順では19番目という
// --limit でいちばん落ちやすい位置にある。
//
// 「移動」の行は [CatVanished] にも出たままにする。候補の作り方を変えるだけで
// 「台本から消えた行」の件数が動くと、いちばん確かな判定がいちばん当てにならない
// 候補に引きずられるため。数が重なることはカテゴリの説明文で先に伝える。
// 「複製」の行は旧キーがいまも再生順にあるので、そもそも重ならない。
//
// 旧版を取り出せないとき（git が無い、リポジトリでない、履歴が1版しかない）は
// 候補を出さずに保留する。[Summary.canJudge] が false になり、「0 件」ではなく
// 理由を書く。0 件と書くと「移すべき訳は無い」と読まれ、翻訳者は訳を捨てる。
//
// 引き継ぎ元の候補:
//
// [CatCarryFrom] は、作業コピーにある未翻訳の行に「公開ファイルのどの行から訳を
// 持ってこられるか」を添える。根拠はコミットされている data/script_order.csv の
// norm 列（正規化した英文のハッシュ）と fp 列（指紋）で、git の履歴もゲーム側の
// 台本も要らない。
//
// 引き継ぎ候補（[CatCarryover]）とは向きも根拠も逆である。あちらは1つ前の版の
// 再生順を git から読み、公開ファイルの旧行に「引き継ぎ先の新キー」を添える。
// 両方あるのは、効く場面が違うからである。
//
// ゲームが更新されてから data/script_order.csv がコミットされるまでのあいだ、
// 新しいキーは再生順のどこにも無く、作業コピーにだけ現れる。この窓では
// 引き継ぎ候補は何も言えない（git の履歴にあるのはどちらも更新前の版だから）。
// 一方、翻訳者の画面にはその行が「未翻訳」として並ぶだけで、同じ台詞の訳が
// 公開ファイルに残っていることはどこにも出ない。訳がいちばん失われるのは
// この窓である。
//
// 突き合わせと、どこで黙るかは carryfrom.go に書いてある。要点は3つ。
//
//   - 正規化して一致した行（書式と記号だけの違い）と、指紋が近い行の2段に分け、
//     どちらで当たったかを注記に書く。確かさが違う。
//   - 決められないときは黙る。正規化すると同じになる別々の英文が再生順に2つ
//     あるときや、指紋が同じ距離で並んで話者でも絞れないときである。
//   - 引き継ぎ元に訳が無ければ出さない。持ってくるものが無い。
//
// norm 列を持たない版の script_order.csv もある（上流の tools/rekey.py augment が
// 後から足した列）。そのときは「0 件」ではなく理由を書く。
//
// タグの開閉:
//
// [CatTagUnbalanced] は訳の中で開始タグに終了が無い行と、終了タグだけがある行を
// 出す（[CheckTags]）。原文とは比べない。原文が <size=80%> や <i> を閉じずに
// 使う行（実データの公開ファイルで各ロケール 51〜53 行）も、訳が同じ書き方なら
// 当たる。だから重さは参考にしてあり、dwloc diff の終了コードには効かない。
// 見つけたいのは <i> の閉じ忘れのような打ち間違いで、画面（internal/web）の
// 絞り込みで拾う。判定は訳だけで済むので、画面は保存のたびにその行だけ判定し直す。
//
// 原文とタグの構成:
//
// [CatTagMismatch] は原文にあるタグが訳に無い行と、原文に無いタグが訳にある行を
// 出す（[CompareTags]）。開閉（[CatTagUnbalanced]）と分けてあるのは、要る材料と
// 直し方が違うからである。開閉は訳だけで判定できるが、こちらは原文が要るので
// 作業コピーしか見られない。直すときも、訳の中で閉じるのではなく原文の構造へ
// 合わせる。
//
// この検査を足したのは、ここが誰も機械で見ていない場所だったからである。翻訳
// リポジトリの CONTRIBUTING.ja.md は「書式タグが原文と同じ構造かどうかは、この
// チェックでは調べていません。レビューで確認します」と書いており、Pull Request
// 前の確認も人手の項目として並んでいる。開閉だけでは、対になったタグが丸ごと
// 落ちている行と、原文に無いタグを足した行が通ってしまう（実データでは、同じ
// キーの行のタグ構成が16ロケールのあいだで4件そろっておらず、うち2件は開閉が
// そろっているぶん既存の判定に掛からない）。
//
// 重さは要確認にしてある。原文と同じ構成なら当たらないので、[CatTagUnbalanced]
// のように毎回当たって終了コードを常に非 0 にすることはない。作業コピーの無い
// CI では判定そのものが起きない。
//
// はみ出しの恐れ:
//
// [CatLayoutRisk] は、ゲーム内の F1 → Translation → Check translation layout が
// 書いた Translations/_discovered/layout_risks.csv を行に結び付ける（layout.go）。
// 読むのは、直す作業がこの道具の中で起きるからである。別の CSV を開いて比の
// 大きい行を探し、原文か訳の文字を頼りに画面へ戻る手間が要らなくなる。
//
// このファイルはロケールの列を持たない。ゲームでそのとき選んでいた言語の結果が
// 1つのファイルへ上書きで書かれる。だから「いま読んでいるロケールの結果」と
// 決めつけず、記録の translation 列がそのロケールの同じキーの訳と1字も違わない
// ことを確かめてから結び付ける。確かめられない行は数にも入れない。別の言語で
// 測った結果を別の言語の警告として出すと、直しようのない指摘になる。
//
// 同じ副作用として、訳を直した行はその場で外れる。測ったのは直す前の訳なので、
// 直した訳がまだはみ出すかどうかはこの道具には分からない。もう一度ゲームで
// 測ってもらう。
//
// 記録が無いことと、記録が空であることは区別する。前者は「測っていない」で、
// [Summary.canJudge] が false になる。後者は「測ったがはみ出す行は無かった」で、
// 0 件と書ける。
//
// 意図的に検出しないもの:
//
//   - 再生順に line_id があるのに公開CSVに対応する台詞ID行が無いこと。
//     台詞ID行は同じ英文を複数の話者が話すときに訳し分けるための任意の行で、
//     空が既定の正常状態（事前調査レポート 3.2 の2番目）。ここを検出に加えると
//     1ロケールあたり最大1839件の誤検出が一気に出る。設計上いちばん壊れやすい
//     箇所なので、規則ではなくテスト（TestRealDataEmptyLineIDsAreNotReported）で守る。
//   - 公開ファイル側の形式不備。internal/validate の CheckFile が既に拾う。
//
// 走らせる順番:
//
// data/script_order.csv を更新したあと、dwloc publish より先に走らせること。
// publish は再生順に置けなかった行の section を 'UI' に書き直すため、
// [CatVanished] の根拠が publish 後には弱くなる（speaker が残るので
// [CatScriptGap] へ落ちるが、確度は下がる）。
//
// [CatCarryover] は publish の影響を受けない。公開行の section も node も見ず、
// 新旧の再生順の line_id だけで決めるため。ただし再生順の更新をコミットして
// しまうと、1つ前の版は「コミットの1つ前」から取ることになるので、その間に
// 再生順を2回コミットすると1回分を飛び越す。更新したらまず走らせるのが安全。
