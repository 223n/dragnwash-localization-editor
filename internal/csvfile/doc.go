// Package csvfile は、この移植で扱うCSVの読み書きをまとめる。
//
// 元実装には性質の違うCSV読み込みが3つある。同じファイルを読ませても結果が
// 食い違うため、「どのツールの挙動を再現したいか」で使い分ける。ファイル名や
// 拡張子では決まらない。
//
//   - [ReadCSharpRows]
//     src/DragNWashLocalization/CsvReader.cs（ゲーム内で動くMod）の再現。
//     レコードの先頭にある '#' だけをコメントとして扱う。引用符の中の '#' は
//     ただの文字。引用フィールド内の改行を値として保持する。どんな壊れた入力でも
//     エラーを返さず、必ず何らかの結果を返す。
//
//   - [ReadPowerShellRows]
//     tools/hash-strings.ps1 の Read-Csv（公開CSVの生成）の再現。
//     行頭が '#' の物理行を機械的に落としてから、1物理行を1レコードとして
//     パースする。引用フィールド内の改行はサポートされない（物理行ごとに
//     別レコードへ割れる）。ヘッダー名の重複だけはエラーになる。
//
//   - [ReadPythonRecords] / [ParsePythonRecords]
//     tools/check-translations.py（形式検証）の再現。基準は上流の dev。
//     元の物理行番号を覚えたまま、Python の csv モジュールと同じ状態機械で
//     パースする。コメントかどうかは引用符の偶奇を行をまたいで持ち回って
//     物理行で決め、コメント行はパーサーに渡さない。完全な空行だけを捨て、
//     空白だけの行はレコードとして残す。報告メッセージの行番号がこの
//     対応付けに依存する。
//
// 3つとも Go の encoding/csv では再現できない。encoding/csv は
// LazyQuotes を立てないと引用符で囲まないフィールド中の二重引用符でパースが
// 止まり、FieldsPerRecord を -1 にしないと列数不一致でエラーになり、BOM を
// 剥がさず、引用フィールド内の CRLF を LF へ潰す。立てても埋まらない差
// （引用がフィールド途中で開始・終了できる、`""` だけの行を空行として捨てる等）
// が残るため、3つとも手書きの状態機械として移植してある。
// 移植仕様「CSVとキー生成 R18」参照。
//
// 書き出しは1通りしかない。[EscapeField] と [AppendLine] を使う。
// 値にカンマ・二重引用符・CR・LF のいずれかを含むときだけ引用符で囲む規則で、
// Go の csv.Writer とは引用条件が違うため、そちらは使ってはいけない。
// 改行は常に LF。
//
// 列名の照合は、どの読み込み方式でも大文字小文字を区別しない（[Row] を参照）。
