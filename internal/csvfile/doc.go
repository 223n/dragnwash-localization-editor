// Package csvfile は、この移植で扱うCSVの読み書きをまとめる。
//
// 元実装には性質の違うCSV読み込みが3つある。同じファイルを読ませても結果が
// 食い違うため、「どのツールの挙動を再現したいか」で使い分ける。ファイル名や
// 拡張子では決まらない。
//
//   - [ReadCSharpRows]
//     src/DragNWashLocalization/CsvReader.cs（ゲーム内で動くMod）の再現。
//     レコードの先頭にある '#' だけをコメントとして扱う。引用符の中の '#' は
//     ただの文字。引用フィールド内の改行を値として保持する。どんな壊れた入力でも
//     エラーを返さず、必ず何らかの結果を返す。
//
//   - [ReadPowerShell]
//     tools/hash-strings.ps1（公開CSVの生成）の Read-Csv の再現で、基準は上流 main。
//     上流は f816618 から、ファイル全体を1つの文字列として ConvertFrom-Csv に渡す。
//     引用符で囲んだ値は物理行をまたいで1つの値になり、引用の外の空行・空白だけの
//     行・'#' で始まる行は落ちる。閉じない引用符と列名の重複は型付きの誤り
//     （[UnclosedQuoteError]、[DuplicateColumnError]）で、値は返さない。壊れた
//     ファイルを画面に並べるときだけ、誤りにせず印を付けて返す
//     [ReadPowerShellMarked] を使う。
//
//     publish・diff・order は、全体を解釈する読み手へ移す作業（docs/port-spec.md）の
//     PR2 からこの読み手で読む（行だけが要る使い手は [PowerShellFile.Rows]）。
//     edit は PR3 から、区切りの関数（[SplitSegments]）のセグメントを行にし、
//     レコードの最終フィールドを差し替えて保存する。
//
//     [ReadPowerShellRows] は、移植の基準 003ed1e の行単位の読み方（'#' の物理行を
//     落としてから、1物理行を1レコードとして読む）で、引用フィールド内の改行を
//     扱えない。どの使い手も使っていない。「どのレコードも1行に収まるファイルでは、
//     全体を解釈する読み方と結果が同じ」ことを確かめる回帰試験と、上流との突き合わせの
//     表のためにだけ残す。[ReadPowerShellWhole] は、PR1 まで publish の守りが行単位の
//     読み違いを見つけるのに使っていた全文の読み方で、主の読み手と同じ区切りに載る
//     （誤りを返さない点だけが違う）。PR2 で守りが主の読み手へ移り、これもどの使い手も
//     使っていない。
//
//   - [ReadPythonRecords] / [ParsePythonRecords]
//     tools/check-translations.py（形式検証）の再現。基準は上流の dev。
//     元の物理行番号を覚えたまま、Python の csv モジュールと同じ状態機械で
//     パースする。コメントかどうかは引用符の偶奇を行をまたいで持ち回って
//     物理行で決め、コメント行はパーサーに渡さない。完全な空行だけを捨て、
//     空白だけの行はレコードとして残す。報告メッセージの行番号がこの
//     対応付けに依存する。
//
// 3つとも Go の encoding/csv では再現できない。encoding/csv は
// LazyQuotes を立てないと引用符で囲まないフィールド中の二重引用符でパースが
// 止まり、FieldsPerRecord を -1 にしないと列数不一致でエラーになり、BOM を
// 剥がさず、引用フィールド内の CRLF を LF へ潰す。立てても埋まらない差
// （引用がフィールド途中で開始・終了できる、`""` だけの行を空行として捨てる等）
// が残るため、3つとも手書きの状態機械として移植してある。
// 移植仕様「CSVとキー生成 R18」参照。
//
// # 区切りの関数
//
// 全体を解釈する読み方の規則（物理行の分け方、境目の空行とコメントの落とし方、
// 引用の開き方、閉じない引用符の扱い）は、[SplitSegments] だけが持つ。ファイルを
// コメント行・空行・レコードのセグメントに分け、それぞれに通し番号の ID、物理行の
// 範囲、本体のバイト範囲、元の終端、フィールドの開始位置を付ける。主の読み手も
// 守り専用の読み手もこの結果に載る。保存（internal/edit）も PR3 からここに載り、
// レコードの最終フィールドの開始位置から本体の終わりまでを差し替える。書く側と
// 読む側で区切りを別々に持つと、最終フィールドの位置がずれて、訳ではない値を
// 書き換えるためである。
//
// 行の同定には ID を使い、物理行の番号は表示と報告の照合にだけ使う。ほかの
// レコードの値に改行が増えると行番号はずれるが、ID は変わらない。
//
// # 形の検出
//
// 読み手は規則どおりに読むだけで、引用符の閉じ誤りと正当な複数行の値を
// 見分けない。見分けは次の関数が形を見て行い、止めるかどうかは呼び出し側が
// 決める。物理行を単独で読むときは行単位の読み方（[ParsePowerShellRecord] と
// [FieldOffsets] の中身）を使う。行単位の読み方をパッケージに残すのはこのためである。
//
//   - [FindSwallows]: 引用符が別の行で閉じ、後ろの行を値に飲み込んだと見られる形
//   - [FindCRCuts]: 引用符で囲まない値が単独の CR で切れたと見られる形
//   - [LoneCRValues]: 値の中の単独の CR
//   - [LineBreakValues]: 見出しに使う値の中の改行（publish が再生順のデータに使う）
//   - [CSharpDisagreements]: ゲームの読み方と値が割れるレコード
//
// # 書き出し
//
// 書き出しは1通りしかない。[EscapeField] と [AppendLine] を使う。
// 値にカンマ・二重引用符・CR・LF のいずれかを含むときだけ引用符で囲む規則で、
// Go の csv.Writer とは引用条件が違うため、そちらは使ってはいけない。
// レコードの区切りは常に LF。値の中の改行（LF・CRLF・単独の CR）は変えずに、
// 引用符で囲んでそのまま書く。
//
// 列名の照合は、どの読み込み方式でも大文字小文字を区別しない（[Row] を参照）。
