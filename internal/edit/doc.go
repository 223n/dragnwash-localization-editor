// Package edit は翻訳ファイルを「セグメント（レコード）の列」として扱う編集モデルである。
//
// 設計の中心は次の1文に集約される。
//
//	保存は「触ったレコードの最終フィールドだけを差し替える」。触っていない部分は1バイトも変えない。
//
// この規則が成り立つ根拠は3つある。
//
//  1. translation は必ず最終列である。validate.AcceptedHeaders() の3種
//     （6列 / 3列 / 2列）も、作業コピーの7列
//     （key,section,node,order,speaker,source_en,translation）も、
//     いずれも最終列が translation。だから「最終フィールドを差し替える」だけで
//     どの形のファイルでも訳を書き戻せる。
//  2. 作業コピーは素のCSVではない。src/DragNWashLocalization/WorkingCopy.cs が
//     ScriptOrder.WriteOrdered 経由で `# ===== ... =====` と `# --- ... ---` の
//     見出しと空行を書くので、公開ファイルと同じ姿になる。コメント行・空行・レコードを
//     同じ並びの要素として扱えば、どちらも同じ扱いで済む。
//  3. csvfile.SplitSegments が既に「ファイルを隙間も重なりも無くセグメントに分け、
//     各セグメントの本体のバイト範囲・終端・物理行の範囲・フィールドの開始位置を
//     返す」。publish（csvfile.ReadPowerShell）も同じ区切りの関数の上で読むので、
//     edit が書き換える範囲と publish が読むレコードが、実装の偶然ではなく構造で
//     一致する。
//
// なぜ再生成（internal/publish）を通さずに保存するのか。再生成は並びと見出しを
// 作り直すうえ、訳が空の行を出力しない。訳を打ち直している途中の自動保存で
// 「訳が空になった行」が丸ごと消える。翻訳者の作業を失うので、編集では通さない。
// コミット前に公開ファイルを作るのは従来どおり publish の仕事である。
//
// # 行は ID で引く
//
// [File.SetTranslation] と [File.Line] は、行（セグメント）の ID で引く。ID は
// セグメントの通し番号（1始まり）で、自分の保存では変わらない（決まったことの 2）。
// 物理行の番号（[Line.Number] と [Line.EndNumber]）は表示と報告の照合にだけ使う。
// 引用符で囲んだ値に改行があるレコードは複数の物理行にまたがり、ほかのレコードの
// 値の改行が増えれば、後ろのレコードの行番号がずれる。ID はずれない。
//
// 画面（internal/web）は ID とキーの両方で行を指す。キーの無い行も ID で決まる。
// 行をまたぐレコードも画面では1行で、行番号の欄に最初の物理行と「〜最後の物理行」を
// 出すのは照合のためだけである。
//
// 一時期、キー（先頭フィールド）で引いて別のファイルへ書き戻す道（WriteByKey）を
// 置いていた。dwloc edit --game が、画面の並べているゲーム側の作業コピーと、
// コミットする側の公開ファイルの両方へ書くためだった。取り下げてある。
//
// 取り下げた理由は、書き戻す先の行が無いからである。publish は訳が空の行を公開
// ファイルに書かない（移植仕様 R20）ので、未翻訳の行は公開ファイルに存在しない。
// キーで引けるのは「すでに訳のある行を直すとき」だけで、翻訳者がいちばんやりたい
// 「未訳の行を訳す」は1行も書き戻せない。それでも画面には保存できたと返るので、
// 訳がどこへ入ったのかを取り違えさせる。新しい訳がコミットする側へ入るのは
// publish を回したときである。
//
// 実装上の約束:
//
//   - 行は csvfile.SplitSegments が分けたセグメントの生のバイト列（終端を含む）を
//     そのまま保持し、書き出しはそれを連結するだけ。編集したレコードだけを組み直す。
//     これが「触っていない部分は1バイトも変わらない」ことの根拠になる。改行が
//     CRLF か LF か、末尾に改行があるか、といった判断をどこにも書かずに済む。
//   - 書き換えるのは、レコードの最終フィールドの開始位置（区切りの関数の Offsets の
//     最後）から本体の終わりまでで、元の終端（CRLF など）はそのまま残す。原文が
//     行をまたぐレコードも書ける。
//   - 訳には改行を入れられる（決まったことの 1）。値の中の CRLF と単独の CR は LF に
//     そろえ（[LFLineBreaks]）、改行の入った訳は引用符で囲んで書く。作業コピーのレコードの
//     区切りが CRLF でも、値の中は LF になる（実物のゲーム側の作業コピーと同じ形。決まった
//     ことのそのほか 1）。改行のぶんだけそのレコードの物理行の数が変わり、後ろの行の
//     行番号がずれる（[File.SetTranslation] がモデルの行番号をずらす）。ID は変わらない。
//   - 書いた訳の行（多くは改行の後ろの行）が、その行だけで読むとレコードに見えるときは
//     （飲み込みの疑い。csvfile.FindSwallows）、書かずに訳の何行目かを返す
//     （reason.EditLineLooksLikeRecord）。publish は同じ関数でそのレコードを止める。
//   - 先頭の BOM は区切りの関数が数えるので覚えておき、書き出しで戻す。
//   - 版は「バイト列全体の SHA-256」。保存前に対象ファイルを読み直して照合し、
//     違えば1バイトも書かずに [ConflictError] を返す。
//   - 書く前の事後確認（決まったことのそのほか 4）を2段で行う。[File.SetTranslation] は
//     差し替えたレコードだけを読み直し（区切りの関数とゲームの読み方の両方で、訳より
//     前の値と終わる位置と物理行の数が変わらず、訳を書いた値として読むこと）、外れたら
//     書き換えずに [NotEditableError] を行ごとに返す。[File.Save] は書く直前に、書こうと
//     しているバイト列をファイル全体として1回読み直し、セグメントの数・ID・物理行の範囲・
//     触っていない行のバイト列が変わらず、書き換えたレコードが飲み込みの疑いにも
//     ゲームの読み方との食い違いにも当たらないこと、書き換えたレコードのほかは、ゲームの
//     読み方（CsvReader の移植）で読んだ値が保存の前後で変わらないことを確かめる。外れたら
//     1バイトも書かずに、行を特定できる [RecheckError] を返す。セグメント・ID・バイト列・
//     値の確かめは、正しく組み立てたバイト列では外れない（外れるのは組み立てに誤りがある
//     ときだけで、その誤りをファイルへ運ばないための守りである）。形の確かめは、正しく
//     組み立てても外れることがある。値が改行で終わる列を持つレコードに、カンマで始まる訳を
//     書くと、続きの物理行を単独で読んだときヘッダーと同じ列の数に見え、飲み込みの疑いに
//     当たる。ゲームの読み方の確かめは、引用符の崩れたレコードの後ろにある、キーも原文も
//     空のレコード（ゲームが引かないので食い違いの判定に入らない）の訳を書き換えたときに
//     外れていた。ゲームの引用の閉じる位置が動き、触っていない後ろのレコードをゲームが
//     見つけられなくなる（PR3 の検証で見つけた）。いまはそのレコードを編集させない
//     （決まったことの 24）ので、判定をすり抜けた書き換えを捕まえる守りとして残す。
//   - 書く直前の確かめが外れたとき、書き換えたレコードが2つ以上なら、1つずつ（ほかの
//     書き換えを戻したバイト列で）確かめ直し、それだけでも外れる最初のレコードを
//     [RecheckError] で指す（[File.culprit]）。上のキーも原文も空のレコードが書けたころ、
//     そのレコードと後ろのレコードを1回の保存で書き換えると、外れるのは後ろのレコードの
//     食い違いとしてで、外れたところから決めると、単独なら書ける後ろのレコードを指して
//     いた（PR3 の検証の指摘）。どれも単独では外れないときは、外れたところに最も近い
//     書き換えたレコードを指す。
//   - 行の種類（見出し・空行・ヘッダー・データ）は区切りの関数のセグメントの種類で
//     決める。引用符で囲んだ値の中の '#' の行や空行を、見出しや区切りと取り違えない。
//   - ヘッダーの受理は生テキストの完全一致のまま（header.go の matchHeader）。
//     どの行をヘッダーにするかだけを区切りの関数にそろえた（決まったことのそのほか 8）。
//   - 開いた引用符がファイルの終わりまで閉じないファイルは、全体を読み取り専用にし
//     （reason.EditUnclosedQuote）、引用符が開いたセグメントから後ろを、レコードとして
//     解釈しない生の行のまま1物理行ずつ並べる（決まったことの 3）。そこを訳として書くと、
//     後ろの行を丸ごと値に飲み込んだまま publish へ渡る。
//   - 行の区切りがすべて単独の CR のファイルは、全体を読み取り専用にする
//     （reason.EditCROnly）。ゲームの読み方（CsvReader）は引用の外の CR を捨てるので、
//     このファイルを1行と読む。
//
// 次のレコードは、理由を付けて編集させない。どれも、書いた訳を publish かゲームが
// 翻訳者の見ている値と別の値に読むか、publish が捨てる形である。形の検出は publish と
// 同じ関数（csvfile の detect.go）を呼ぶ。理由は直す先を指す順に1つだけ付ける
// （順の理由は [File.judge] の注記）。
//
//   - 列の数がヘッダーと合わない（reason.EditFieldCount）。
//   - 飲み込みの疑い（csvfile.FindSwallows。reason.EditSwallow）。引用符の閉じ誤りで、
//     後ろの行（英語の原文やキー）を値に飲み込んでいる疑い。正当な複数行の値でも
//     当たるが、画面には確かめたうえで通す指定を置かない。
//   - ゲームの読み方との食い違い（csvfile.CSharpDisagreements。
//     reason.EditGameDisagrees と reason.EditGameMissesRecord）。フィールドの途中の
//     '"'、引用の外の単独の CR などで割れる。
//   - publish がキーを決められない（reason.EditNoKeyOrSource。決まったことの 24）。
//     原文（source_en。トリムしない）が空で、key 列（前後の空白を除く）が台詞ID でも、
//     小文字にして16桁の16進でもないレコード。2列の `hello,訳`、6列の `abc,UI,,,UI,訳`、
//     7列の `hello,UI,,,UI,,訳` や `,UI,,,UI,,訳` など。source_en 列の無い形では原文は
//     空と同じに見る。publish がこのレコードを捨てる（移植仕様 R17）ので、書いた訳は
//     公開されない。判定は publish と同じ関数（publish.Keyless）を呼ぶ。原文があって
//     key 列と合わないレコード（R15）は、publish が捨てても当てない（diff が「publish で
//     捨てられる行」として知らせる）。訳の入ったこのレコードで publish がどうなるかは、
//     開いているファイルで違う。作業コピーなら、集計の malformed dropped に数えるだけで
//     止まらず、訳は黙って落ちる。作業コピーの無いロケールで公開ファイル自身を開いて
//     いるとき（publish の入力と書き出し先が同じ）は、失われる訳の確かめ
//     （publish.CheckLoss）がこのレコードを拾い、publish はどのロケールも書かずに止まる。
//     画面は訳を空にする書き換えも断るので、止まった状態は key 列を直すか行を消すかを
//     手で行ってほどく。
//
// 訳に改行（CR か LF）があるレコードは、PR3 のあいだ編集させなかった
// （reason.EditMultilineTranslation）。画面が改行を空白に置き換えていたので、開いて1字
// 打つと、翻訳者が見ていない改行まで消えたためである。PR4 で画面が改行を残すように
// なったので、この理由は無くした。
//
// 値がどれも空になるレコード（"," や `""`、",,,,,," の行）は空行相当にし、編集させない
// （改善の ui-15）。キーも原文も空なので publish が捨て（移植仕様 R17）、打った訳は
// 公開されない。訳など、ほかの列に値のあるレコードは空行相当にならないが、上の publish
// がキーを決められない理由で編集させない。編集できるレコードには、原文か、16桁のキーか
// 台詞ID の key 列があるので、訳を消しても空行相当にはならない（PR3 のはじめは、2列で
// キーの空いた行の訳を消すと空行相当に変わり、それを断らなかった）。
//
// 既知の非対称（元実装から引き継ぐもの）:
//
//   - 値に '#' で始まる訳を入れても最終列なので問題は起きない。先頭列に '#' が
//     来るとコメントとして消えるが、このパッケージは先頭列を書き換えない。
