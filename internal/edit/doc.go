// Package edit は翻訳ファイルを「物理行の列」として扱う編集モデルである。
//
// 設計の中心は次の1文に集約される。
//
//	保存は「触った行の最終フィールドだけを差し替える」。触っていない行は1バイトも変えない。
//
// この規則が成り立つ根拠は3つある。
//
//  1. translation は必ず最終列である。validate.AcceptedHeaders() の3種
//     （6列 / 3列 / 2列）も、作業コピーの7列
//     （key,section,node,order,speaker,source_en,translation）も、
//     いずれも最終列が translation。だから「最終フィールドを差し替える」だけで
//     どの形のファイルでも訳を書き戻せる。
//  2. 作業コピーは素のCSVではない。src/DragNWashLocalization/WorkingCopy.cs が
//     ScriptOrder.WriteOrdered 経由で `# ===== ... =====` と `# --- ... ---` の
//     見出しと空行を書くので、公開ファイルと同じ姿になる。行単位で扱えば
//     どちらも同じ扱いで済む。
//  3. csvfile.SplitPythonLines が既に「改行を保ったまま物理行と1始まりの行番号を
//     返す」。読みの側に足すものは無い。
//
// なぜ再生成（internal/publish）を通さずに保存するのか。再生成は並びと見出しを
// 作り直すうえ、訳が空の行を出力しない。訳を打ち直している途中の自動保存で
// 「訳が空になった行」が丸ごと消える。翻訳者の作業を失うので、編集では通さない。
// コミット前に公開ファイルを作るのは従来どおり publish の仕事である。
//
// # 行は行番号で引く
//
// [File.SetTranslation] は行番号で引く。画面が並べているファイルには、画面が
// 行番号を持っているからである。引き方はこれ1つでよい。
//
// 一時期、キー（先頭フィールド）で引いて別のファイルへ書き戻す道（WriteByKey）を
// 置いていた。dwloc edit --game が、画面の並べているゲーム側の作業コピーと、
// コミットする側の公開ファイルの両方へ書くためだった。取り下げてある。
//
// 取り下げた理由は、書き戻す先の行が無いからである。publish は訳が空の行を公開
// ファイルに書かない（移植仕様 R20）ので、未翻訳の行は公開ファイルに存在しない。
// キーで引けるのは「すでに訳のある行を直すとき」だけで、翻訳者がいちばんやりたい
// 「未訳の行を訳す」は1行も書き戻せない。それでも画面には保存できたと返るので、
// 訳がどこへ入ったのかを取り違えさせる。新しい訳がコミットする側へ入るのは
// publish を回したときである。
//
// 実装上の約束:
//
//   - 行は csvfile.SplitPythonLines が返した生のテキスト（改行文字を含む）を
//     そのまま保持し、書き出しはそれを連結するだけ。編集した行だけを組み直す。
//     これが「触っていない行は1バイトも変わらない」ことの根拠になる。改行が
//     CRLF か LF か、末尾に改行があるか、といった判断をどこにも書かずに済む。
//   - 先頭の BOM は剥がして覚えておき、書き出しで戻す。csvfile.SplitPythonLines が
//     BOM を落とすので、覚えておかないと BOM 付きファイルで1行目が変わってしまう。
//   - 版は「バイト列全体の SHA-256」。保存前に対象ファイルを読み直して照合し、
//     違えば1バイトも書かずに [ConflictError] を返す。
//   - 行の種類（見出し・空行・ヘッダー・データ行）は、publish と同じ全体を解釈する
//     読み方の区切り（csvfile.SplitSegments）で決める。引用符で囲んだ値の中の '#' の
//     行や空行を、見出しや区切りと取り違えないためである。1物理行に収まるレコードの
//     値は csvfile.ParsePowerShellRecord で読む（1行に収まるレコードでは、区切りの
//     関数と同じ値になる）。
//   - 保存の単位は物理行のままである。複数の物理行にまたがるレコードは、どの物理行も
//     理由（reason.EditMultiline）を付けて編集させない。1行目へ書くと続きの行が残り、
//     publish の読み方では壊れたレコードになるからである。1行目には全体を解釈して
//     読んだ値を持たせ、キーと原文の全体を画面に出す。レコードの単位で保存するのは
//     全体を解釈する読み手へ移す作業の PR3 である。
//   - 開いた引用符がファイルの終わりまで閉じないファイルは、全体を読み取り専用にし
//     （reason.EditUnclosedQuote）、引用符が開いたレコードから後ろを、レコードとして
//     解釈しない生の行のまま並べる（決まったことの 3）。そこを訳として書くと、後ろの
//     行を丸ごと値に飲み込んだまま publish へ渡る。
//   - ヘッダーの受理は生テキストの完全一致のまま（header.go の matchHeader）。
//     どの行をヘッダーにするかだけを区切りの関数にそろえた（決まったことのそのほか 8）。
//   - 書き戻す位置は csvfile.FieldOffsets で求める。ParsePowerShellRecord は
//     末尾の空フィールドを落とすので、未訳行（`a,b,` の形）の最終フィールドの
//     位置を出せない。FieldOffsets はそれを落とさない。
//
// 既知の非対称（元実装から引き継ぐもの）:
//
//   - 訳の前後の空白は、書いたとおりには読み戻せない。csvfile.EscapeField は
//     空白を引用符で囲わず、ConvertFrom-Csv 側は引用符なしフィールドの先頭空白を
//     全除去・末尾空白を1個残して除去する。したがって " x  " と書くと次に読んだ
//     ときは "x " になる。[File.SetTranslation] は書き戻したあとの行を読み直して
//     モデルを更新するので、画面に出る値と保存された値は常に一致する。
//   - 値に '#' で始まる訳を入れても最終列なので問題は起きない。先頭列に '#' が
//     来るとコメントとして消えるが、このパッケージは先頭列を書き換えない。
