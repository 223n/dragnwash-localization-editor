// Package edit は翻訳ファイルを「セグメント（レコード）の列」として扱う編集モデルである。
//
// 設計の中心は次の1文に集約される。
//
//	保存は「触ったレコードの最終フィールドだけを差し替える」。触っていない部分は1バイトも変えない。
//
// この規則が成り立つ根拠は3つある。
//
//  1. translation は必ず最終列である。validate.AcceptedHeaders() の3種
//     （6列 / 3列 / 2列）も、作業コピーの7列
//     （key,section,node,order,speaker,source_en,translation）も、
//     いずれも最終列が translation。だから「最終フィールドを差し替える」だけで
//     どの形のファイルでも訳を書き戻せる。
//  2. 作業コピーは素のCSVではない。src/DragNWashLocalization/WorkingCopy.cs が
//     ScriptOrder.WriteOrdered 経由で `# ===== ... =====` と `# --- ... ---` の
//     見出しと空行を書くので、公開ファイルと同じ姿になる。コメント行・空行・レコードを
//     同じ並びの要素として扱えば、どちらも同じ扱いで済む。
//  3. csvfile.SplitSegments が既に「ファイルを隙間も重なりも無くセグメントに分け、
//     各セグメントの本体のバイト範囲・終端・物理行の範囲・フィールドの開始位置を
//     返す」。publish（csvfile.ReadPowerShell）も同じ区切りの関数の上で読むので、
//     edit が書き換える範囲と publish が読むレコードが、実装の偶然ではなく構造で
//     一致する。
//
// なぜ再生成（internal/publish）を通さずに保存するのか。再生成は並びと見出しを
// 作り直すうえ、訳が空の行を出力しない。訳を打ち直している途中の自動保存で
// 「訳が空になった行」が丸ごと消える。翻訳者の作業を失うので、編集では通さない。
// コミット前に公開ファイルを作るのは従来どおり publish の仕事である。
//
// # 行は ID で引く
//
// [File.SetTranslation] と [File.Line] は、行（セグメント）の ID で引く。ID は
// セグメントの通し番号（1始まり）で、自分の保存では変わらない（決まったことの 2）。
// 物理行の番号（[Line.Number] と [Line.EndNumber]）は表示と報告の照合にだけ使う。
// 引用符で囲んだ値に改行があるレコードは複数の物理行にまたがり、ほかのレコードの
// 値の改行が増えれば、後ろのレコードの行番号がずれる。ID はずれない。
//
// 画面（internal/web）は ID とキーの両方で行を指す。キーの無い行も ID で決まる。
//
// 一時期、キー（先頭フィールド）で引いて別のファイルへ書き戻す道（WriteByKey）を
// 置いていた。dwloc edit --game が、画面の並べているゲーム側の作業コピーと、
// コミットする側の公開ファイルの両方へ書くためだった。取り下げてある。
//
// 取り下げた理由は、書き戻す先の行が無いからである。publish は訳が空の行を公開
// ファイルに書かない（移植仕様 R20）ので、未翻訳の行は公開ファイルに存在しない。
// キーで引けるのは「すでに訳のある行を直すとき」だけで、翻訳者がいちばんやりたい
// 「未訳の行を訳す」は1行も書き戻せない。それでも画面には保存できたと返るので、
// 訳がどこへ入ったのかを取り違えさせる。新しい訳がコミットする側へ入るのは
// publish を回したときである。
//
// 実装上の約束:
//
//   - 行は csvfile.SplitSegments が分けたセグメントの生のバイト列（終端を含む）を
//     そのまま保持し、書き出しはそれを連結するだけ。編集したレコードだけを組み直す。
//     これが「触っていない部分は1バイトも変わらない」ことの根拠になる。改行が
//     CRLF か LF か、末尾に改行があるか、といった判断をどこにも書かずに済む。
//   - 書き換えるのは、レコードの最終フィールドの開始位置（区切りの関数の Offsets の
//     最後）から本体の終わりまでで、元の終端（CRLF など）はそのまま残す。原文が
//     行をまたぐレコードも、訳が1行に収まるかぎり書ける。
//   - 先頭の BOM は区切りの関数が数えるので覚えておき、書き出しで戻す。
//   - 版は「バイト列全体の SHA-256」。保存前に対象ファイルを読み直して照合し、
//     違えば1バイトも書かずに [ConflictError] を返す。
//   - 行の種類（見出し・空行・ヘッダー・データ）は区切りの関数のセグメントの種類で
//     決める。引用符で囲んだ値の中の '#' の行や空行を、見出しや区切りと取り違えない。
//   - ヘッダーの受理は生テキストの完全一致のまま（header.go の matchHeader）。
//     どの行をヘッダーにするかだけを区切りの関数にそろえた（決まったことのそのほか 8）。
//   - 開いた引用符がファイルの終わりまで閉じないファイルは、全体を読み取り専用にし
//     （reason.EditUnclosedQuote）、引用符が開いたセグメントから後ろを、レコードとして
//     解釈しない生の行のまま1物理行ずつ並べる（決まったことの 3）。そこを訳として書くと、
//     後ろの行を丸ごと値に飲み込んだまま publish へ渡る。
//   - 訳に改行（CR か LF）があるレコードは、訳への改行の入力を足すまで（PR4）編集
//     させない（reason.EditMultilineTranslation）。いまの画面は改行を空白に置き換える
//     ので、開いて1字打つと、翻訳者が見ていない改行まで消える。
//
// 既知の非対称（元実装から引き継ぐもの）:
//
//   - 値に '#' で始まる訳を入れても最終列なので問題は起きない。先頭列に '#' が
//     来るとコメントとして消えるが、このパッケージは先頭列を書き換えない。
