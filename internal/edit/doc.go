// 訳の空のレコードが1件あります。
//
// ヘッダーが source_en,translation の2列だけのファイルは読み取り専用になります。
// tools/hash-strings.ps1 はこの形を入力として受け付けるので、いずれ編集できて
// よい形ですが、受理するヘッダーを増やすかどうかは別の判断として残します。
// 最終列が translation である点は変わらないので、モデル自体は成り立ちます。
