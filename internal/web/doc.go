// Package web は翻訳ファイルを1画面に並べて見せる、手元だけの待ち受けである。
//
// 訳を書き換えて保存できる。保存は自動で、入力が止まったときと欄から離れたときに
// 走る。publish は回さない。
//
// # 保存の経路
//
// 画面が並べるのは [publish.DiscoverTargetsWithGame] が返した Target.Input である。
// 作業コピーがあればそれ、無ければ公開ファイル自身。行番号も版（baseVersion）も
// このファイルのもので、409 の判定もこのファイルで行う。
//
// 保存先はこの Target.Input 1つだけである。publish が入力に選ぶファイルと同じなので、
// 画面で直したものは次の publish でそのまま公開ファイルになる。
//
// # なぜ2つ書きをやめたか
//
// 一時期、ゲーム側の作業コピーを開いているときは、コミットする側の公開ファイルへも
// キーで同じ訳を書き戻していた。これは成り立たない。
//
// publish は訳が空の行を公開ファイルに書かない（移植仕様 R20）。したがって未翻訳の
// 行は公開ファイルに存在しない。実機で数えると、ja.working.csv で訳が空のキーは32件、
// そのどれ1つとして Translations/ja/strings.csv に行が無かった（internal/publish の
// doc.go に数え方を書いてある）。
//
// つまり、翻訳者がいちばんやりたいこと——未訳の行を訳す——は、キーで引いても
// 書き戻す先の行が無く、コミットする側へ1行も入らない。それでも画面は saved=true を
// 返し、「未翻訳」の件数も減るので、進んだように見える。黙って落とすより悪い。
//
// 新しい訳がコミットする側へ入るのは publish を回したときである。そのことは画面の
// 断り書き（note.via_publish）と、起動時の1行（server.publish_hint）で伝える。
//
// 並べているのがゲームのフォルダーの作業コピーのときは、どちらも --game の付いた
// 文言（note.via_publish_game / server.publish_hint_game）に替える。ゲーム側を
// 読んでいるのに「dwloc publish を回してください」と書くと、そのとおり打った
// publish は公開ファイル自身を入力にして「変更なし」で終わる。訳は失われないので
// [publish.CheckLoss] も止めず、入らなかったことに気づく手がかりが1バイトも出ない。
// 言い分けの根拠は [publish.Target] の GameBase で、あれが埋まるのは入力がゲーム側
// から来たときだけである（server.go の hasGameWorkingCopy）。
//
// # ゲームのフォルダー
//
// [Options] の Game にゲーム側のプラグインフォルダーが入っていると、作業コピーの
// 探し先にそこが加わり、そちらが先に当たる。原文（source_en）の欄が埋まるのも、
// 「未翻訳」を数えられるのも、作業コピーを読めたときだけである。リポジトリの
// Translations/_discovered は .gitignore で外してあるので、ここが空だとふつうは
// 空振りする。
//
// そのため cmd/dwloc の edit は、--game を省かれても自分で探してここへ入れる
// （resolveGameForEdit）。publish と diff は省かれたら探さない。この待ち受けは
// どちらの経路で決まった値も同じに扱い、空かどうかだけを見る。
//
// 探し先は /api/bootstrap の game に載せ、画面の上に出す（app.js の showGamePath）。
// 「使っています」とは書かない。そのロケールの作業コピーがそこに無ければ1バイトも
// 読まないためである。実際に読み書きするファイルは、ロケールごとに
// linesResponse.Path に出る。出すのはパスだけで、原文と訳は記録にも誤りの応答にも
// 入れない。
//
// ゲームは C:/Program Files (x86)/ の下に入ることが多く、書き込みを拒まれうる。
// 拒まれたときは [edit.File.Save] が短い間隔で3回まで試し、それでも書けなければ
// 503 を返す。そのとき行ごとの saved も倒す。画面は未保存の控えを捨てずに送り直す。
//
// publish は回さない。保存は「触った行の最終フィールドだけを差し替える」であって
// 再生成ではない。再生成すると並びと見出しが作り直され、訳を打ち直す途中の
// 自動保存で「訳が空になった行」が丸ごと消える。publish を回すのは翻訳者の判断で、
// あちらには書き出す前の守り（publish.CheckLoss）が付いている。
//
// # 訳を失わない
//
// この待ち受けでいちばん重い約束である。
//
//   - 版（ファイル全体の SHA-256）が合わなければ1バイトも書かず、409 と現在の
//     行一覧を返す。画面はそれを描いたうえで、どちらの編集を載せるかを人に選ばせる。
//     黙って上書きも、黙って破棄もしない。
//   - 行ごとに結果を返す。1行が書けなくても、残りは書く。書けなかった行は
//     理由を添えて返し、画面はその行を「保存できていない行」として残す。画面は
//     理由だけでなく値も控える。控えないと、その訳は欄の字としてしか残らず、
//     入力欄を開き直す・競合を解く・読み直すのどれでも行は描き直されて古い
//     保存値が出るので、1字打った瞬間に上書きされる。
//   - 競合している行は、どちらを残すか人が選ぶまで編集させない。選ばせる前の
//     入力は、どちらのボタンの意味にも取れてしまう。詳しくは
//     「## 競合している行は、選ぶまで開かない」に書いた。
//   - 1行も書けなかったときは 422 を返す。黙って成功したように見せない。
//   - 行はキーでも同定する。要求は行番号とキーの両方を載せ、その行番号に別の
//     キーの行があれば書かずに断る。行番号だけで書くと、409 のあとの載せ直しで
//     訳が別の行へ入り、その行にもとからあった訳が消える。
//   - 保存の送り直しを途中で諦めない。画面は間隔を広げながら送り続ける。諦めると、
//     原因（ゲームがファイルを開いている）が消えたあともその訳は送られない。
//   - 載せる先の行がファイルから無くなった訳は、捨てずに画面へ出し続ける。
//     そこが、その訳が残っている最後の場所になる。
//   - 未保存のまま頁を閉じようとしたら、画面が beforeunload で止める。
//   - 読み直しとロケールの切り替えは、送れるものを送り終えてから、それでも残る訳が
//     あるときだけ「その訳は消えます」と尋ねる。押した時点で決めていたころは、
//     打った直後に押すと尋ねたり尋ねなかったりし、尋ねた訳が送られてファイルに
//     入った。受けたあとは、読み込みのあいだに送り直しの時計が切れてもその訳を
//     送らない。読めなければ送り直しへ戻す（app.js の askDiscard と load）。
//   - 書き出し（別の場所へ保存）は、ファイルに入っていない訳（送り終えていない訳、
//     競合、保存できない行、行き先の無い訳）が残っているあいだは中身を取りにいかず、
//     何を片付ければよいかを言う。取りにいくと、画面に出ている訳の入らない中身を
//     「書き出しました」と渡す。
//
// # 書き込みの守り
//
// POST には Origin の完全一致と Content-Type: application/json を要求する
// （[server.checkWrite]）。素のフォーム送信はこの2つを満たせないので、他の頁から
// 書き込ませることができない。Cookie が SameSite=Strict であることと合わせて3本。
//
// # 入力欄
//
// 焦点が入った1行にだけ、頁に1つだけ作った入力欄を差し込む。1721行ぶんの入力欄を
// 常設すると、開くだけで重くなる。入力欄は spellcheck / autocorrect /
// autocapitalize / autocomplete をすべて切る。ブラウザーの綴り検査は、内蔵翻訳と
// 同じく入力の中身を外部のサービスへ送りうる経路である。
//
// ## 競合している行は、選ぶまで開かない
//
// 409 のあと、画面は「自分の訳を上に載せる」と「ファイルの訳を採る」を出して人に
// 選ばせる。選ばれるまでのあいだ、競合している行（自分の編集を抱えている行）は
// 編集させない。訳欄を押しても入力欄は開かず、Tab の行き先にもならない。行には
// 「ファイルの訳: … / あなたの訳: …」に続けて「どちらを残すか選んでから直せます」
// と出す（目録の ui.conflict_locked）。
//
// 開かせていた。競合の最中でも直せるほうが親切に見えたからである。だが、どちらを
// 残すか決まっていない行への入力は、2つのボタンのどちらの意味にも取れる。起点を
// どちらに寄せても、押したボタンと違う結果になる道が残った。
//
//   - 起点をファイルの訳にすると、1字打った瞬間に自分の版が控え（pending）を
//     上書きし、自分の訳は画面のどこにも出なくなった。「自分の訳を上に載せる」を
//     押しても、それはもう捨てられていた（行き先が見つからない訳の一覧にも
//     入らない）。
//   - そこで起点を自分の訳に変えた。今度は、いったん離れてもう一度開くと、その
//     あいだに打ち直した訳（pending）が捨てられ、入力欄は競合が起きた時点の訳に
//     戻った。さらに悪いことに、その状態で「ファイルの訳を採る」を押すと、
//     takeFile は pending を残すので、ファイルの訳ではなく自分の競合版がファイルへ
//     書かれた。押したボタンと逆の結果である。
//
// 2つ目は、1つ目を直したときに作った穴である。曖昧さを別の側へ動かしただけで、
// 曖昧さそのものは残っていた。だから、曖昧な状態を作らないことにした。
//
// 選ばせてからにすると、keepMine は「抱えていたぶんを控えへ足す」だけ、takeFile は
// 「抱えていたぶんを捨てて、控えはそのまま」だけになり、どちらのボタンも押した
// とおりに効く。実際のファイルのバイトで確かめてある（競合行はボタンどおりに
// なり、競合していない行へ選んでいるあいだに打った訳は、どちらを押しても残る）。
//
// 翻訳者が「両方を見て新しい訳を書きたい」ときは、片方を選んでから直すことになり、
// 2手になる。押したボタンと違う結果が出るほうが重い事故なので、こちらを選ぶ。
//
// 止めるのは、決まっていない行だけである。競合の引き止めが出ているあいだも、
// 競合していない行はいつもどおり編集できる。競合のあいだ自動保存は止まって
// いるので、そこで打った訳はブラウザーの中にしかない。だから、どちらのボタンを
// 押してもその訳は残す。
//
// ## 選ばせるのは、よそが本当に書き換えた行だけ
//
// 409 は「ファイル全体の版が合わない」という意味しか持たない。よそが触ったのが
// こちらの触っていない行でも 409 になる。そこで onConflict は、抱えている未保存の
// 訳を、読み直した内容の上へキーで載せ直したうえで2つに分ける。
//
//   - その行についてこちらが最後に見たファイルの値と、読み直した値が違う
//     → よそが書き換えた。選ばせる対象（state.mine）にする
//   - 同じ → よそは触っていない。未保存のまま（state.pending）残し、
//     読み直した版の上へ保存し直す
//
// 分けないと、409 が続けて起きたときに訳が消える。1度目の競合の最中に打った訳は
// 控えに入るが、2度目の 409 でそれも「競合したもの」へ移り、「ファイルの訳を採る」
// で一緒に捨てられる。実測で、翻訳者が打った訳がファイルにも画面にも残らず、
// 行き先の無い訳の一覧にも入らず、beforeunload の引き止めも効かない形になった。
// ボタンのすぐ上に「選んでいるあいだに打った訳は、どちらを選んでも残ります」と
// 書いてあるのに、その逆が起きていた。
//
// 分けた結果、選ばせる対象が1行も無いこともある（よそが触ったのが、こちらが
// 触っていない行だけだったとき）。そのときは引き止めを出さず、読み直した版の上へ
// そのまま保存し直す。人に選ばせることが無いからで、黙って上書きしているのでは
// ない。書き込む前に待ち受けがもう一度版を照合するし、こちらが触っていない行は
// 1バイトも触らない。すぐに送らず自動保存の時計を通すのは、よそが書き続けて
// いるあいだ 409 と再送で回り続けないようにするためである。
//
// ## 決断のボタンは帯の先頭に出す
//
// 貼り付く帯（.top）は max-height: 50vh で頭打ちにしてあり、あふれたぶんは帯の中で
// スクロールする。画面が狭い・低いと bar が何段にも折り返し、その下にある引き止めが
// 帯の外へ沈む。実測で、600x500 と 320x600 では「ファイルの訳を採る」に
// elementFromPoint が当たらず、実際に押しても何も起きなかった。絞り込みの一帯を
// 帯の外へ出しても、この形は残っていた（外へ出す判断のときに測ったのは 800x600 の
// 1点だけで、そこでは押せていた）。
//
// 引き止めが出ているあいだ自動保存は止まっている。ボタンに手が届かないことは、
// 打ち続けられるのに1バイトも保存されない状態が続くことを意味する。だから
// #conflict だけ order を負にして、帯の中でいちばん先に出す。HTML の並びは
// 変えない。読み上げと焦点の順はそのままにして、見た目の順だけを変える。
// 焦点の順と見た目の順が食い違うのは承知のうえで、引き止めが出ているときに
// いちばん先に見えるべきものがこれだからである。
//
// 先頭に出しても、狭くて低い画面では足りなかった。幅が狭いと説明の文
// （ui.conflict_help）が長く折り返し、2つ目のボタンが帯の見える範囲の下へ出る。
// 実測（Chromium）で、320x500 の帯は 0〜250px、「ファイルの訳を採る」は 248〜279px
// にあり、elementFromPoint が当たらなかった（320x480、360x480、414x480 も同じ）。
// 帯の中を送れば届くが、送れることは画面のどこにも出ない。だから2つのボタンを
// 1つの箱にまとめ、帯の中で下端に貼り付ける（app.css の .conflict-actions）。
// ボタンがもともと見える範囲にあれば動かず、下にあるときだけ説明の文の上に重なる。
//
// 打っていた行そのものが競合したときは、入力欄を開き直せない（選ぶまで開かない）。
// 焦点を body へ落とすと、続けて打った字は黙ってどこにも入らないので、引き止めの
// 枠そのもの（#conflict、tabindex="-1"）へ焦点を移す。ボタンへは移さない。続けて
// 打った Space や Enter（日本語の入力では変換と確定）がボタンを押し、よそが書いた
// 訳を読まないまま「自分の訳を上に載せる」を選んでしまうためである。
//
// # 外してはいけない性質
//
// 元のプロジェクトは「ゲームの英語の台本を再配布しない」ことを設計の中心に
// 据えている（docs/research.md 7.2 が Weblate を採れない理由として挙げている点）。
// この待ち受けはその台本を画面に出す道具なので、次を守る。
//
//   - 外向きの通信を1バイトも行わない。このパッケージは net/http.Client を持たない。
//     更新確認も、フォントも、スクリプトも、外から取らない。画面の資産はすべて
//     [uiFS] に埋めてある。守られていることは TestNoOutboundHTTP が字面で見張る。
//   - 原文と訳をログに書かない。要求の記録は、--verbose なら画面へ、付けなくても
//     ログファイル（logs/dwloc_<日付>.log）へ残る。書く中身はどちらも同じで、
//     メソッド・パス（問い合わせ文字列を除く）・状態コード・所要時間・ロケール名・
//     件数だけにする。誤りの応答にも panic からの復帰にも行の中身を載せない。
//     最初の1回の URL に載るトークンは、ファイルからは伏せる（[Options.HideFromRecord]）。
//     ログファイルはそのまま不具合の報告に貼れるものでなければならない。
//   - 画面の題名に原文を入れない。題名はブラウザーの履歴に残る。
//   - 原文を URL に載せない。クライアントが指定できるのはロケール名だけである。
//   - API の応答に Cache-Control: no-store を付ける。ディスクキャッシュに残さない。
//   - ブラウザー内蔵の翻訳と綴り検査を止める。どちらも画面と入力の文字列を
//     外部のサービスへ送りうる。CSP はこの頁が出す通信しか塞げない。
//
// # 絞り込みと検索
//
// 1721行から「いま直すべき行」へ早く着くための2つである。どちらもブラウザーの
// 中だけで終わる。待ち受けは1つも経路を増やしていない。
//
// ## 条件は複数選べる
//
// 状態バッジのカテゴリと、「未保存」「保存できない」の2つを並べ、選ばれた
// どれかに当たった行を出す（論理和）。1つだけ選ばせる形にしなかったのは、
// 1行が複数のカテゴリに当たるためである。「未翻訳」と「引き継ぎ候補」は
// 別のカテゴリだが、翻訳者にとってはどちらも「いま手を入れる行」で、
// 1つずつしか選べないと同じ画面を2周することになる。行き来のたびに
// 画面の位置も失う。
//
// 条件の一覧は [countView] から組む。カテゴリ名も並びも待ち受けが返したもので、
// 画面は定義し直さない。internal/diff にカテゴリが増えれば、画面の条件も黙って
// 増える。判定できていないカテゴリも条件として出す。選んでも1行も出ないが、
// その理由は件数の欄が「判定していません（…）」と言っている。「行が無いから
// 外す」と画面で決めると、それが画面の独自判断になる。
//
// ## 検索は待ち受けに聞かない
//
// 当てるのは speaker / 原文 / 訳 / キーで、打った字を含む行だけを出す。行は
// すでにブラウザーの中にあるので、待ち受けに聞く必要がそもそも無い。聞けば、
// 検索語（＝原文の断片）が要求の経路に乗り、記録（画面とログファイル）に残りうる。
// URL にも載せない。URL はブラウザーの履歴に残り、待ち受けが終わったあとも
// 残る。localStorage にも sessionStorage にも残さない。どちらもディスクに残る。
//
// 検索の入力欄は、訳の入力欄と同じく spellcheck / autocorrect / autocapitalize /
// autocomplete / translate を全部切る。綴り検査は入力の中身を外部のサービスへ
// 送りうる経路である。type も text にする。search にすると、ブラウザーに
// よっては前に打った語を候補として出し、その候補はブラウザー側に残る。
//
// ## 絞り込みは左の列に置く
//
// 条件と検索は、貼り付く .top の中ではなく、左の列（.sidebar）に置く。列は
// 帯の外にあるので、帯の高さにも一覧の始まりにも関わらない。広い画面では
// 列が帯の下に貼り付いて自分の中でスクロールし、狭い画面（900px 以下）では
// 引き出しになって、帯のボタン（#menu）かスラッシュで開く。列には、畳んだ
// 説明（キー操作、絞り込みの断り書き、起動したときの状態の一帯）も入れてある。
// 一覧を押し下げはしなくなったが、畳んだままにしてある。開いたままだと条件の
// 下に長い文が居座り、条件が列の中でスクロールアウトする。
//
// 狭い画面で引き出しが閉じているあいだは、列に inert を付けて焦点を入れさせない。
// 閉じた引き出しは画面の外へ出してあるだけなので、付けずにいたころは Tab で
// 画面の外の検索の欄やチップに焦点が入り、見えない欄に打った字で一覧だけが黙って
// 絞られた。開けば入れる。広い画面の列には付けない。
//
// 見た目は管理画面（AdminLTE）風にしてあるが、枠組みは使っていない。同梱すると
// その CSS の中の URL（data: の xmlns など）が「資産に URL を置かない」試験と
// 食い違い、実行ファイルも太る。アイコンは Font Awesome Free の図形だけを
// index.html に埋め、帰属表示を THIRD_PARTY_NOTICES.md に置いた。
//
// 以下は、列へ移す前に一帯をどこに置くかを決めた経緯である。帯の中に入れて
// はいけない理由は、列にしたいまも同じである。
//
// ### 絞り込みの一帯は貼り付けない
//
// 貼り付けていた。1721行のどこを見ていても条件を変えられるようにするためで、
// 考え方としては悪くない。だが .top は max-height: 50vh で止めてあるので、
// 中身が増えたぶんだけ下のものが帯の中で押し出される。
//
// 800x600 で 409 を起こした状態を、同じ頁で両方の形にして測った（Chromium）。
//
//	一帯を外に出したいま  帯の高さも中身も 245px。「自分の訳を上に載せる」は
//	                      画面の 198.4px にあり、elementFromPoint がそのボタンを返す。
//	一帯を帯の中へ戻すと  中身は 396px になるのに帯は 300px（50vh）で止まる。
//	                      ボタンは 349.7〜382.1px、つまり帯の下端より下に沈み、
//	                      elementFromPoint は一覧の行を返す。
//
// 貼り付いているのに押せない、といういちばん悪い形である。絞り込みの一帯だけで、
// 実測 1280x900 で 126.2px、800x600 で 151.3px、375x812 で 252.1px（画面の 31%）
// あった。
//
// 条件をいつでも触れることより、競合のボタンがいつでも押せることのほうが重い。
// 競合のあいだ自動保存は止まっているので、ボタンが押せないあいだ、その訳は
// ブラウザーの中だけにある。だから一帯を外へ出し、.top に残すのは bar /
// message / conflict / orphans の4つだけにした。外へ出したあとの .top の高さは
// 実測で、1280x900 と 800x600 が 49.4px、375x812 が 92.4px、320x600 が 121.4px
// である。
//
// 条件へ戻る道は2つで補っている。1つはスラッシュの近道で、検索の欄へ焦点を
// 移したあとにこの一帯を画面へ送る（scrollIntoView）。順番を逆にすると、
// そのあとの focus がブラウザーの既定の送り方で上書きし、検索の欄が帯の下へ
// 潜る。もう1つは「表示中 N 行」で、これだけは貼り付く帯のほうへ移した。
// 絞り込みの唯一の手応えなので、条件の一帯まで戻らないと見えないのでは使えない。
//
// ## 未保存の行と、触っている行は隠さない
//
// 絞り込みでも検索でも、未保存の訳がある行・保存できなかった行・競合で
// 抱えている行・いま入力欄が開いている行は、条件に当たらなくても必ず出す。
// 隠すと、直すべき行が画面から消える。しかも翻訳者は、消えたことに気づけない。
// 自動保存があるので未保存が残るのは保存できなかったときと競合中だけだが、
// その2つはまさに人が見て直さなければならない状態である。訳を失わないという
// 約束は、絞り込みより重い。
//
// 4つ目（いま入力欄が開いている行）は、検索の待ちと入力欄の開きが重なる事故の
// 直しである。以前は「条件で行が消えるとき、その行の入力欄が開いていたら先に
// 保存してから閉じる」形にしていた。それが打鍵を捨てた。検索欄に打ってから
// 120ms 以内に行の訳欄をクリックすると、入力欄が開いた直後に当て直しが走り、
// まだ1字も打っていない（＝未保存でない）その行を閉じて隠した。焦点は body へ
// 落ち、以後打った字はどこにも入らないのに、保存の欄は「保存済み」のまま、
// 警告は1つも出なかった。
//
// 触っている行を隠さないことにすると、入力欄を差し込んだまま行が隠れる道が
// 無くなる。だから当て直しの中で入力欄を閉じる処理そのものが要らなくなり、
// 消してある。戻すときは、この経路をもう一度ブラウザーで踏んでから戻すこと。
//
// ## 閉じた行は、そこだけ照らし直す
//
// 入力欄を閉じたあと、その行がまだ出す行かどうかを確かめる。出す行でなければ、
// そこで条件を当て直す。確かめないと、条件に当たらない行が一覧に残り、
// 「表示中 N 行」もその1行を数えたままになる。食い違いは、翻訳者が次に条件を
// 触るまで消えない。
//
// 「閉じるたびに当て直す」にはしなかった。上から順に Enter で打っていくとき、
// 閉じる時点のその行はまだ未保存なので、当て直しは走らない。走らせると、数行前に
// 打ち終わって保存が済んだ行が条件から外れて次々に消え、一覧が1行ぶんずつせり
// 上がる。それは「保存のたびには当て直さない」（訳し終えた行が目の前で消えない
// ようにする）と決めたことを、1行遅れでやり直すだけになる。
//
// 呼ぶ順番も実際に踏んで決めた。Enter の行送りでは、次の行を開いてから照らし直す。
// 逆にすると、照らし直しの時点で「いま開いている行」が空なので、これから開く行が
// 条件に当たらなければその場で隠れる。そのあと入力欄が隠れた行へ差し込まれ、
// 焦点は入っているのに欄は見えない。実測では、「未保存」で絞った状態で保存済みの
// 行から Enter を押すと、入力欄は行番号 41 の行に入ったのに、その行は hidden、
// 入力欄の高さは 0、一覧は「条件に合う行がありません」になった。打った字は
// どこにも見えないまま入る。上の「触っている行を隠さない」で塞いだはずの穴を、
// 順番ひとつで開け直していたことになる。
//
// ## 1行も出ないときは、そう言う
//
// 条件や検索に1行も当たらないと、一覧は真っ白になる。手がかりが「表示中 0 行」
// だけだと、壊れたのか条件に当たっていないのかが読み取れず、直し方も画面に
// 無い。だから一覧の場所に「条件に合う行がありません。条件を外すと全部出ます」
// と出す（目録の ui.no_rows）。
//
// 検索の欄に字が入っているときは、そちらを先に言う（目録の ui.no_rows_search）。
// 「条件を外すと全部出ます」は、検索語のせいで0行になったときには嘘になる。実データ
// の de で zzzznotfound と打つと、条件を1つも選んでいないのに0行になり、外す条件が
// 無いのに条件を外せと言われる（外しても0行のままである）。まず検索の欄を空にすれば
// 戻る、と言うほうが次の一手になる。空にしてなお0行なら、そのときに条件のほうの
// 文言が出る。見ているのは検索の欄に字があるかどうかだけで、数は数えていない。
//
// ロケールを切り替えたら、条件と検索語は外す。持ち越すと、ja で打った検索語の
// まま ko へ移ったときに、ヘッダーが「行: 1713」と言っているのに一覧が空になる。
// 条件はそのロケールを見ながら決めたものである。読み直しでは外さない（同じ
// ロケールを見続けている）。
//
// 外すのは、読めたときだけである。切り替えの手前で外していたころは、読み込みに
// 失敗すると条件と検索欄だけが空になり、チップの checked と一覧は前のロケールの
// まま残った（実測で「チップ2つが選ばれたまま、一覧は前のロケールの 110 行の
// まま、表示中 110 行のまま」になった）。失敗したときは何も変わっていないのが
// 正しい。読めたときは、画面を描き直す手前で外す（チップの checked は
// state.filter から作られるので、あとから外すと一覧とチップがずれる）。
//
// ## 保存のたびには当て直さない
//
// 条件は、翻訳者が決めた時点の写しのままにしておく。保存のたびに当て直すと、
// いま訳し終えた行が「未翻訳」の条件から外れて目の前で消える。読み直したときと、
// 条件を触ったときにだけ当て直す。バッジと件数が起動時の1回であることと同じ
// 考え方で、画面は自分から並びを変えない。
//
// ## 出ている行数は件数と混ぜない
//
// 「表示中 N 行」は上の帯に、件数の欄とは別の文言で出す。件数は internal/diff が
// 判定した数で、こちらは画面が出している行の数である。同じ場所に並べると、
// 後者が前者の内訳に見える。数え上げそのものは forEach の中で n = n + 1 と
// 書く。[TestUIDoesNotCount] が見張っているのは「画面がカテゴリや状態を
// 導き出さないこと」なので、待ち受けが決めた出し入れの結果を数えるのは
// この約束とぶつからない（その説明は試験のコメントにも書いてある）。
//
// ## 条件のチップに添える数は、この一覧にあるその条件の行数
//
// チップに書くのは [countView.Rows]、いま並べているファイルの中でそのカテゴリの
// バッジが付いているデータ行の数である。件数（[countView.Count]、internal/diff が
// 見つけた数）は書かない。実データ（ja、公開ファイルを並べているとき）では、
// 「どのロケールにも訳が無い行」が件数32に対して0行だった。チップに32と書いて
// 押させ、1行も出ないのは嘘になる。
//
// 食い違うかどうかは --game の有無ではなく、いま並べているのが公開ファイルか
// 作業コピーかで決まる。実データで作業コピーがあるのは ja だけなので、
// --game を付けても残り15ロケールは公開ファイルを並べ、同じ食い違いが出る
// （16ロケール × 2通りの32本を GET して確かめた）。
//
// 単位も分ける。件数の欄は「N 件」、チップは「（N 行）」と書く。同じ数の
// 言い換えではなく、別のものを数えた別の数だからである。
//
// 数える先が違うだけで、どちらも正しい。件数は消さない。2つが食い違うカテゴリ
// では、件数の欄のその行に「32 件（この一覧には 0 行）」と両方を書く
// （目録の ui.count_and_rows）。食い違っているかどうかを決めるのは待ち受けで、
// [countView.RowsDiffer] に入れて渡す。画面が Count と Rows を比べて書き分けると、
// それが待ち受けとは別の判断になる。実データ（ja、公開ファイル）で、この形に
// なるのは9カテゴリのうち1つだけである。作業コピーを並べているあいだは、
// 9カテゴリとも件数と行数が一致した。件数の欄の同じ文は、チップの添え書き
// （title）にもそのまま入れる。2つの数は画面の離れた2か所に出るので、押す手の
// 下でもう一方が読めるようにしておく。
//
// ### 「押したときに並ぶ行数」ではない
//
// 当初はそう約束しようとしたが、実機で測ると常に破れた。破るのはどれも待ち受けが
// 知らない画面の状態で、数に入れようとした時点で画面が数える側に回る。約束の
// ほうを、破れない形に直した。チップの数は「いま並べている一覧の中で、その条件に
// 当たる行が何行あるか」である。実測（実データの写し、ja）:
//
//   - 保存。訳を1行入れるとチップは「32 行」→「31 行」になるが、一覧は組み直さ
//     ないので 32 行のまま並ぶ。27 行まで訳し進めると、チップ「未翻訳（0 行）」の
//     下に 27 行が並んだ。組み直さないのは、打っている最中に行が目の前から消えない
//     ようにするためである（app.js の applyView）。並んでいる行のバッジはその場で
//     消えるので、「もう当たらない行が残っている」とは読める。
//   - 隠さない行（app.js の keepAlways）。入力欄を1つ開いたまま「台本に無い台詞行
//     （17 行）」を押すと 18 行出た。18行目にそのバッジは無い。訳している最中は
//     入力欄が必ず1つ開いているので、この道具をふつうに使っているあいだ常に起きる。
//   - 検索語。「未翻訳（27 行）」のまま kobold と打つと 4 行になった。de で
//     zzzznotfound と打つと「由来を判定できない行（93 行）」を押して 0 行になる。
//
// どれも「数が嘘」ではなく「一覧が数と別の時点・別の条件を映している」である。
// いま何行出ているかを言うのは上の帯の「表示中 N 行」だけ、と役割を1つに絞る。
// 合計欄も作らない（条件を2つ選ぶと和集合なので、数は足し算にならない）。
//
// 数が何の数なのかは、畳めない見出し（目録の ui.filter、「絞り込み（括弧の数は、
// この一覧にある行数）」）に置く。畳みの summary に置いていたが、そこは既定で
// 閉じている。見出しは 1280幅でも375幅でもそれだけで1行を占めているので、ここへ
// 字を足しても一帯は高くならなかった（1280幅 151.3px、375幅 327.7px、いずれも
// 増減なし）。ただし 375幅では 23字を超えると折り返し、一帯が 22.4px 高くなる。
// 足すときは測ること。ずれる3つは断り書き（ui.finder_note）に書く。
//
// ### 0 と書かないカテゴリが2つある
//
// 判定できていないカテゴリのチップには数を出さず「（未判定）」と書く。押せば
// 0行なのは本当だが、「（0 行）」と書くと「もう何も残っていない」と読まれる。
// 0 と書かないのは件数の欄がもともと守っている約束で（[server.buildCounts] と
// internal/diff の doc.go）、作業コピーが無いあいだ「未翻訳」がこれになる。
//
// 判定はできているのに、この一覧には1行も出せないカテゴリも同じである
// （[countView.NoRowHere]）。チップには「（この一覧には出せません）」と書く。
// 公開ファイルを並べているときの「どのロケールにも訳が無い行」が 32件／0行 で
// これになり、「（0 行）」と書くと、片付いていないどころか「このロケールのファイルに
// そのキーの行が無い」という逆の意味が0に化ける。どちらに書き分けるかを決めるのは
// 待ち受けで、画面に Count > 0 && Rows == 0 を比べさせない（RowsDiffer と同じ）。
//
// ### 保存のあと
//
// 条件は組み直さずに、数と添え書きだけ写す（app.js の updateChipRows）。組み直すと
// 触っている最中の選択が跳ねる。数を写さないと、チップが「この一覧にあるその条件の
// 行数」でなくなる（バッジは消えているのに、数だけが古い）。
//
// バッジを描き直す先はキーで引く（app.js の renderBadgesForKey）。待ち受けはキー
// 単位でバッジを落とす（[server.badgesByKey]）ので、同じキーの行が2行あるとき、
// 応答に入っている行だけ描き直すと、もう一方が古いバッジを付けたまま残る。実データ
// には重複キーが1件も無いが、作業コピーは Mod が書き出す CSV で、dwloc validate も
// 公開ファイルしか見ない。1174行目を複製して試すと、チップ31に対して32行出た。
//
// 数は [TestChipRowsCountTheBadgedRowsInTheList] が見ている。行として出せない
// 場面は [TestNotPublishedHasNoRowToShow] が見本として持っている。
//
// ## 重さは色だけで伝えない
//
// 条件のチップには、カテゴリ名の前に重さの名前（要作業／要確認／参考）を
// 小さく添える。縁と文字の色だけで重さを伝えていたが、以前の --todo #8a4b00 と
// --review #9a1c1c は色覚によっては近く、app.css の冒頭に書いた「色だけで
// 意味を伝えない」に反していた。名前は [countView.StatusLabel] をそのまま
// 使う。画面の状態の2つ（未保存・保存できない）は待ち受けが重さを持って
// いないので、目録の ui.filter_state（「画面の状態」）を当てる。
// internal/diff の重さと同じ名前を当てないのは、別のものだからである。
//
// ## 読み上げ向けの属性を付ける
//
// 「表示中 N 行」と保存の状態は aria-live="polite"、失敗の理由と「1行も
// ありません」は role="status"、条件の群は role="group" と aria-labelledby を
// 付ける。付ける前は、この頁に aria-live も role=status も1つも無かった。
// 絞り込みの唯一の手応えも、黙って失敗しないという約束も、目で見ている人
// だけのものになっていた。条件の群に名前が無いと、文脈の無いチェックボックスが
// 9個並んでいるようにしか読み上げられない。
//
// 見張り（role="status"）は hidden で出し入れしない。hidden の要素は支援技術の
// 木から外れるので、文字が変わる瞬間にその要素が木に居らず、告知しない実装が
// あり得る。出し入れは中身の入れ替えで行い、空のときは app.css の
// .notice:empty が余白と下線を落とす（中身の無いブロックは行ボックスを作らない
// ので高さは0になる）。
//
// 確かめられているのは、ここまでである。属性が付いていること、hidden で出し
// 入れしていないこと、空のときに場所を取らないことはブラウザーで見た。
// 読み上げソフトで実際に告知されるかどうかは、この環境では確かめていない。
// 「読み上げに出る」ではなく「読み上げに出るための形にしてある」と読むこと。
//
// # 暗い配色
//
// OS の設定（prefers-color-scheme）が暗ければ、:root の色の変数を差し替えて
// 暗くする。画面の中に切り替えは置かない。この道具は画面の状態をどこにも
// 残さないと決めてあり、切り替えを置くと覚える場所が要る。
//
// 色は変数にしか書かない（TestColorsLiveInTokens）。規則の外に色を1つ書くと、
// その場所だけ明るい配色のまま暗い画面に残る。暗い側は明るい側の変数を1つ残らず
// 定義する（TestDarkSchemeRedefinesEveryToken）。意味の色（要作業・要確認・参考・
// 保存の状態）は色みを保ち、名前を必ず出す約束はそのままである。色そのものも、
// 色覚の違い（P型・D型・T型）で見分けられるよう、色相と明度の両方で離してある
// （app.css の :root の注記）。明度比（WCAG のコントラスト比）の計測は app.css の両方の注記にある。
//
// # キー操作
//
// 訳の欄で Enter を押すと、確定して次の（絞り込みで出ている）編集できる行の
// 入力欄が開く。上から順に打っていける形にする。これが翻訳作業のいちばん太い
// 道で、無いと1行ごとにマウスへ手が戻る。隠れている行は飛ばす。飛ばさないと、
// 条件に当たらない行の入力欄が画面の外で開く。競合している行も飛ばす。開かない
// 行を行き先にすると、閉じたあと開かずに戻って焦点が body へ落ちる。
//
// 次の行は、閉じる前に決める。閉じると state.editing が空になるので、順番を
// 逆にすると行き先が分からなくなる。打った訳は入力のたびに未保存の控えへ
// 入っており、閉じるときの保存がまとめて送る。条件の照らし直しは、次の行を
// 開いたあとに回す（「## 閉じた行は、そこだけ照らし直す」を見よ）。
//
// 次の行が無いとき（出ている最後の編集できる行）は、閉じない。その行に留まり、
// 保存だけ走らせる。閉じると焦点が body へ落ち、終わりまで来たという合図も
// 出ないので、キーボードだけで打っている人は自分がどこにいるか分からなくなる。
// 焦点を失わせないほうを採る。
//
// Escape は閉じるだけである。この段でも変えていない。
//
// ## 変換の確定と Enter
//
// 変換中（compositionstart から compositionend、e.isComposing、keyCode 229）は、
// キーを1つも横取りしない。ja / ko / zh-Hans / zh-Hant のためにこの入力方式を
// 選んでいるので、ここが崩れると選定の根拠が失われる。
//
// その3つの見張りだけでは足りない。compositionend が確定の keydown より先に
// 届く並びだと、そのときの Enter は state.composing も e.isComposing も false、
// keyCode は 13 で、素の Enter と1つも区別が付かない。3つとも素通りして次の
// 行が開く。翻訳者から見ると、変換を確定しただけで行が飛ぶ。IME と Enter の
// 古典的な事故である。
//
// だから時刻でも見分ける。compositionend の時刻を控え、そこから 100ms のあいだに
// 来た Enter は、行送りにも欄閉じにも使わない。改行が入らないよう preventDefault
// だけはする。確定とその Enter は同じ1打鍵から出るので間はほぼ0で、投げた事象で
// 測ると 0.0〜0.2ms だった。100ms は、事象の並びがブラウザーや IME で違っても
// 収まる幅として置いた値である。代わりに「確定した直後にもう一度 Enter を押して
// 次の行へ行く」操作は 100ms 待たされるが、行が勝手に飛ぶほうが重い事故なので、
// こちらを選ぶ。
//
// この 100ms が実機で足りることは、Windows の実機の IME で確かめてある
// （dwloc 0.4.1、2026-09-17。変換の確定で行が飛ばず、そのあとの Enter で
// 次の行へ進むことを、実際に打って確かめた）。間隔そのものは実機では測って
// いないので、短くするなら先に測ること。
//
// 時刻は performance.now（経過時間）で測る。Date.now（壁時計）で測ると、確定と
// Enter のあいだに OS の時計が後ろへ動いたとき（NTP の段差、休止からの復帰）、
// 差が負のまま 100ms を超えるまで Enter の行送りが効かなくなる。
//
// ## スラッシュ
//
// 頁全体で受けているスラッシュ（検索の欄へ移る）も、変換中と、入力欄に焦点が
// あるときと、修飾キーが付いているときは効かせない。効くと、その字が訳にも
// 検索語にも打てなくなる。
//
// ただし「入力欄」に、絞り込みのチェックボックスとラジオは数えない。字を打つ
// ところではないからである。数えていたころは、条件に焦点があるあいだスラッシュが
// 効かず、「条件を選んだ直後にスラッシュで検索へ移る」という、いちばんありそうな
// 流れで黙って何も起きなかった。画面の説明（ui.keys_help）のほうは、最初から
// 「入力欄の外でスラッシュを押すと検索の欄へ移ります」と言っていた。
//
// ## 画面へ入れるときの余白
//
// Enter や Tab で行から行へ移ると、ブラウザーは焦点の入った要素を画面へ入れよう
// とする。上の帯は貼り付いているので、余白を取らないとその下へ潜る。
//
// 余白（scroll-margin-top）は、焦点の入る要素に付ける。訳の欄（.translation）と、
// 差し込んだ入力欄（.editor）と、スラッシュの行き先になる絞り込みの一帯
// （.finder）である。行（.row）に付けても1度も使われない。ブラウザーが画面へ
// 入れようとするのは焦点の入った要素であって、その親ではないためで、
// getComputedStyle で見ると .editor の scrollMarginTop は "0px" のままだった。
//
// .finder の余白は、広い画面で列が貼り付く位置（帯の下端から --sidebar-gap）と
// 同じ値にする。8px 狭くしていたころは、scrollIntoView がその差を頁のスクロールで
// 埋めにいき、列は貼り付いているので差は埋まらず、スラッシュを押すたびに一覧が
// 8px ずつ下へずれた（1280x720、scrollY 3000 → 3008 → 3016）。
//
// ## 余白は帯の高さから作る
//
// その余白を 8em（112px）の固定値にしていた。足りない。.top は競合の引き止めと
// 行き先の無い訳が出ると max-height: 50vh まで伸びるからである。実測した帯の高さ
// （Chromium）。
//
//	1280x900 / 800x600   49.4px   競合も行き先の無い訳も出ていないとき
//	375x812              92.4px   帯の中身が2列に折り返す
//	320x600             121.4px   さらに折り返す
//	800x600             150.6px   行き先の無い訳が1件だけ出ているとき
//	800x600 / 320x600   300px     競合と行き先の無い訳の両方（50vh そのもの）
//
// 112px のまま、800x600 で競合と行き先の無い訳を両方出して踏むと、こうなった。
//
//	Shift+Tab    開いた入力欄の上端 238.4px。帯の下端は 300px なので、
//	             elementFromPoint は入力欄ではなく #orphans を返す。
//	スラッシュ   絞り込みの一帯の上端 111.8px、検索の欄の上端 223.7px。
//	             elementFromPoint は #conflict を返す。
//
// 貼り付けるのをやめた代償をスラッシュで補う設計なのに、いちばん補ってほしい
// 競合中に補えていなかった。
//
// だから画面側が ResizeObserver で .top の高さを測り、CSS 変数（--top-height）へ
// 入れる。余白はその値から作る。同じ場面をもう一度踏むと、入力欄の上端は
// 308.4px、検索の欄は 419.7px になり、elementFromPoint はどちらもその要素を返す。
// 幅320pxでも、競合と行き先の無い訳を両方出した状態の Shift+Tab で入力欄の上端は
// 308.1px（帯の下端 300px）だった。
//
// これは配置の測定であって、行やカテゴリの判定ではない。「画面に新しい判断を
// 置かない」が禁じているのは、待ち受けが決めたカテゴリや状態を画面が導き出す
// ことである。要素が画面上で何ピクセルを占めているかは待ち受けが知りようのない
// 値で、ブラウザーに聞くほかにない。internal/diff の判定は1つも触っていない。
//
// 測れない環境（ResizeObserver が無い）では変数が入らないので、CSS の var() の
// 第2引数（10em＝140px）がそのまま効く。既定値は、競合も行き先の無い訳も出て
// いないときの、いちばん狭い幅（320px）の帯（121.4px）を覆う高さにしてある。
// 広い画面の帯（49.4px）に合わせると、狭い画面では余白が帯より低くなり、焦点の
// 入った行が帯の下へ潜る。競合や行き先の無い訳が出て帯が伸びたぶんは覆えない。
//
// 何のキーが効くかは画面に出す（目録の ui.keys_help）。覚えていないと使えない
// 近道は、無いのと同じである。ただし畳んでおく。絞り込みの断り書きと2つで、
// 開いたままだと一覧の始まりが 1280幅で 671.0px → 821.3px、375幅で 1212.6px →
// 1669.9px まで下がる（実データの ja、1721行での実測）。読むのは1度で足りるのに、
// 一覧より上にずっと居座っていたことになる。
//
// 畳みは details/summary で作る。開閉そのものをブラウザーに任せるためで、
// 自前のボタンと hidden で組むと、開閉の状態を読み上げへ伝える仕掛けを自分で
// 持つことになる。既定は閉じた状態（index.html に open を付けない）。開閉は
// 覚えない（この道具は画面の状態をどこにも残さない）。
//
// 畳むと読まれなくなる文がある。閉じたままでも読めるのは summary だけなので、
// そこには「無条件に本当のこと」を入れる。いまは検索がブラウザーの中だけで
// 完結すること（＝打った語がどこにも残らないこと）を入れてある。畳む前の
// #finder-note は常に開いていて、この断りが無操作で読めた。条件つきでしか本当で
// ないことをここに入れると、いちばん読まれる1文がいちばん当てにならない1文になる
// （チップの数の説明を入れていたが、保存・隠さない行・検索の3つで破れた。上の
// 「押したときに並ぶ行数ではない」を見よ）。数が何の数かは、畳めない見出し
// （ui.filter）へ移した。
//
// 文言が入るまでは hidden で出さない（[TestNoticesStartFolded]）。summary は焦点を
// 受ける要素なので、目録が届くまでのあいだ、名前を持たない開閉要素が焦点の順に
// 並ぶ（実測: 空でも高さ 36.19px、tabIndex 0、focus() が通る）。畳みの中身は告知
// する欄ではないので hidden で構わない。role="status" の #message と #empty を
// hidden にしないのとは、逆の理由で分かれている。
//
// ## 一帯は畳みきらない
//
// 起動したときの状態の一帯（.panel）も畳んだ。中身はゲームのフォルダー、断り書き、
// 件数、数えたもので、どれも起動したときに1回だけ決まる値である。上の2つと同じ
// 理由で、開いたままだと一覧より上を占める。実測（実データのリポジトリの ja、
// --game auto で当てた実機のゲームのフォルダー、その作業コピー1753行）で、一帯の
// 高さは、開いたときと閉じたときで 1280幅が 417.7px → 69.8px、375幅（root を
// 375px に絞っての実測）が 899.9px → 137.0px になる。375幅では、開いていると
// 一帯だけで画面（812px）を超えていた。閉じたときの高さは「ファイル」の欄に
// 出るパスの長さで動くので、どのパスで測ったかは ui/index.html の注記に書いてある。
//
// ただし「ファイル」の欄（#file-path）だけは summary の中に置き、畳んだままでも
// 読めるようにしてある。ここはこの画面でいちばん大事な1行で、リポジトリの公開
// ファイルを直しているのか、ゲーム側の作業コピーを直しているのかが、そこにしか
// 出ていない。閉じた details は中身を支援技術の木からも外すので（実測: 閉じた
// 畳みの中の p は checkVisibility() が false）、中へ入れると畳んだ画面から消える。
//
// 絞り込みの断り書きで「閉じたままでも読めるのは summary だけ」としたのと同じ手
// である。あちらは文を、こちらは値を入れてある。押さえは
// [TestPanelFoldKeepsTheFilePathReadable]。
//
// この畳みだけは、出すのが目録の届いた時点ではなく /api/lines を受けた時点である
// （app.js の render）。ほかの2つは summary に入るのが目録の文なので目録で足りるが、
// ここに入るのは「いま読み書きしているファイルの名前」で、それが来るのは
// /api/lines だからである。目録の時点で出すと、--locale を省いた起動（画面で
// ロケールを選ぶ既定の経路。ダブルクリックで開いたときもこれ）で、ロケールを
// 選ぶまで名前の無い畳みが残る。実測: 1280幅で一帯の高さ 47.4px、summary の字は
// 添え字だけ、tabIndex 0、#file-path と #notes と #counts はどれも空。
//
// # 画面に新しい判断を置かない
//
// 状態バッジも件数も、すべて internal/diff の [diff.Report] / [diff.Summary] /
// [diff.Finding] から引く。画面が独自に数え始めた瞬間、diff/doc.go が名指しで
// 警告している誤検出（実データで1430件規模）を作り直すことになる。
//
// 判定できていないカテゴリは [diff.Summary.CanJudge] が false になる。そのときは
// 「0 件」ではなく [diff.Summary.JudgeBlockReason] の理由を、目録を通して出す。
// 0 件と書くと「移すべき訳は無い」と読まれ、翻訳者は訳を捨てる。
//
// 行の並びと見出しも同じ考え方で、internal/edit が読んだ物理行をそのまま出す。
// 見出しは internal/order から組み直さず、ファイルにある `# ===== ... =====` と
// `# --- ... ---` のコメント行を写す。画面は常にファイルの写しになる。
//
// 見出しは3段（section / node / other）で持ち回る。other は、どちらの印も
// 付いていないコメント行である。絞り込みで見出しを出し入れするときは、節が
// 変われば node と other を捨て、節点が変われば other を捨てる。other を
// 捨て忘れると、翻訳者が書いた1行メモが、その下の行が1つも出ていないのに
// 後ろの節点の行の見出しとして出続ける。出荷中の ja/strings.csv では起きないが、
// internal/edit は先頭が # の行をすべてコメントとして扱うので、メモを1行
// 書いた時点で起きる。
//
// # 待ち受けの絞り方
//
// 手元の1人が使う道具なので、外から届く経路を全部塞ぐ。
//
//   - 束ねる先は常に 127.0.0.1 に固定する。--port を指定しても変わらない。
//   - 起動のたびに32バイトのトークンを作り、最初の GET /?t=<トークン> でだけ
//     受け取る。以後は HttpOnly・SameSite=Strict の Cookie で持つ。
//   - Cookie が無い要求には 404 を返す。401 だと「そこに何かがある」と教えてしまう。
//   - Cookie の名前にポートを入れる（[cookieNameFor]）。Cookie はポートで分かれない
//     ので、名前を固定にすると dwloc edit をもう1つ動かしただけで先のトークンが
//     消え、その画面は保存できなくなる。
//   - Host ヘッダーを完全一致で検査する（DNS リバインディングへの対策）。
//   - Sec-Fetch-Site があれば同一生成元だけを通す。CORS のヘッダーは1つも返さない。
//   - 操作が絶えたら自分で終わる。翻訳者の PC に待ち受けを残さない。
package web

// # 理由も目録を通す
//
// 判定できない理由、バッジの注記（行ごとに引き継ぎ先が変わる動的な文を含む）、
// publish で捨てられる理由、他のロケールにある件数、保存できない理由は、
// すべて目録を通ります。カテゴリ名と重さの名前も同じです。
//
// internal/diff と internal/edit は文面のかわりに、識別子と置換の組と
// 組み立て済みの日本語をまとめた [reason.Reason] を返します。文面の組み立ては
// [server.reasonText] が行い、目録の鍵は "reason." + 識別子です。目録に鍵が
// 無ければ、組み立て済みの日本語へ落とします。訳されていない文が出るほうが、
// 何も出ないよりよいからです。
//
// 日本語の文面は internal/diff と internal/edit に残したままにしてあります。
// dwloc diff の text と CSV はその文面をそのまま出しており、--ui-lang があるのは
// edit だけだからです。消すと CLI が壊れます。同じ日本語が ja.json にもあるので、
// 2つの写しがずれないことを TestJapaneseCatalogMatchesTheSourceText が見ています。
//
// # 直していない制限
//
// 英語の画面に日本語が残る経路が、まだ1つあります。
//
//	識別子を持たない「1つ前の再生順を取り出せない理由」
//
// [diff.OldOrderSource] は差し替えられる関数で、返した誤りの文面がそのまま
// 「判定していません（…）」の括弧の中になります。既定の実装（diff.GitOldOrder）が
// 返す番兵には識別子を当ててありますが、再生順の場所をルートからの相対に
// できなかったときだけは、包んだ誤りをそのまま返すので名前がありません。
// その1行は英語の画面でも日本語のまま出ます。
//
// 当てずっぽうで近い識別子を付けるほうが危ういと考えました。別の理由の英文が
// 出ると、翻訳者は違う対処をします。日本語が1行残るほうがましです。
//
// 保存のとき、internal/edit が [edit.NotEditableError] でも
// [edit.InvalidValueError] でもない誤りを返した場合も、その Error() をそのまま
// 出します（[server.editErrorText]）。いまの internal/edit にその経路はありません。
//
// # 状態バッジは起動時の1回
//
// バッジと件数は起動時に diff を1回走らせた結果です。ファイルを読み直しても
// バッジは更新しません。13ロケール全部を読む処理なので、1行開くたびにやり直す
// 種類ではないためです。publish を回したあとは、いったん終了して開き直して
// ください。
//
// 保存したときの更新は、局所的なものだけにしてあります。訳が入ったキーを
// 「未翻訳」の件数から引き、その行から「未翻訳」のバッジを外す。保存した行の
// 「タグの開閉がそろわない行」だけは、いまの訳で判定し直す（訳だけで決まる
// 判定なので、他のロケールを読まずに済みます。[diff.CheckTags]）。それだけです。
// 訳を消せば戻ります。ほかのカテゴリの再判定はしません。できないことは画面の
// 断り書き（note.counts_local）で伝えています。
//
// # 一覧に出ないもの
//
// 「他のロケールにあって無い行」と「どのロケールにも訳が無い行」は、その行が
// このロケールのファイルに無いので、原理的にバッジとして出ません（件数にだけ
// 出ます）。足すべき行をどう見せるかは編集を足す段の課題です。
//
// この2つは、絞り込みの条件としては並びますが、選んでも0行になります。実データ
// （ja、データ行1721）で確かめたところ、バッジが付くのは「台本に無い台詞行」17行と
// 「由来を判定できない行」93行の2カテゴリだけでした。条件から外していないのは、
// 「行が無いから外す」と画面で決めると、それが画面の独自判断になるためです。
//
// 行として出せないことは、チップに「（この一覧には出せません）」と書いてあります。
// 「（0 行）」とは書きません。件数が32あるカテゴリに0と書くと、「もう残っていない」と
// 読めてしまい、実際の意味（このロケールのファイルにその行が無い）と逆になるためです。
// 件数の欄との食い違いも、そのカテゴリの行に「32 件（この一覧には 0 行）」と書いて
// あります。押してから気づくのではなく、押す前に読めるようにするためです。
// 件数の欄の同じ文は、チップの添え書き（title）にも入れてあります。判定できていない
// カテゴリでは、その理由（作業コピーがありません、など）がそこに出ます。
//
// # 絞り込みと検索の速さ
//
// 実測です（データ行1721、見出し202、Windows の Chromium、作業コピーあり）。
//
//	条件の当てはめだけ        0.2〜17ms
//	描き直しまで含めて        最大 173ms（出す行が全行に戻るとき）
//	検索が出した要求          0 件（待ち受けの記録で確かめました）
//
// 打鍵ごとに走らせると描き直しが手に追いつかないので、検索は打ち終わりから
// 120ms 待ってから走らせます。絞り込みの条件は押した時点で走らせます（押す
// 回数はもともと少ないので、待つ理由がありません）。
//
// # 画面側の試験
//
// 画面の振る舞いは Go から動かせないので、internal/web/ui_test.go は字面でしか
// 見ていません。書き方を変えたときは、実際にブラウザーから確かめてください。
// 保証できるぶんは待ち受け側へ寄せてあります（行のずれは TestSaveRejectsMovedRow
// が実ファイルで見ています）。
