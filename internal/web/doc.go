// Package web は翻訳ファイルを1画面に並べて見せる、手元だけの待ち受けである。
//
// この段では読み取り専用である。編集も保存もさせない。
//
// # 外してはいけない性質
//
// 元のプロジェクトは「ゲームの英語の台本を再配布しない」ことを設計の中心に
// 据えている（docs/research.md 7.2 が Weblate を採れない理由として挙げている点）。
// この待ち受けはその台本を画面に出す道具なので、次を守る。
//
//   - 外向きの通信を1バイトも行わない。このパッケージは net/http.Client を持たない。
//     更新確認も、フォントも、スクリプトも、外から取らない。画面の資産はすべて
//     [uiFS] に埋めてある。守られていることは TestNoOutboundHTTP が字面で見張る。
//   - 原文と訳をログに書かない。既定では要求のログを出さない。--verbose でも
//     メソッド・パス（問い合わせ文字列を除く）・状態コード・所要時間・ロケール名・
//     件数だけにする。誤りの応答にも panic からの復帰にも行の中身を載せない。
//   - 画面の題名に原文を入れない。題名はブラウザーの履歴に残る。
//   - 原文を URL に載せない。クライアントが指定できるのはロケール名だけである。
//   - API の応答に Cache-Control: no-store を付ける。ディスクキャッシュに残さない。
//
// # 画面に新しい判断を置かない
//
// 状態バッジも件数も、すべて internal/diff の [diff.Report] / [diff.Summary] /
// [diff.Finding] から引く。画面が独自に数え始めた瞬間、diff/doc.go が名指しで
// 警告している誤検出（実データで1430件規模）を作り直すことになる。
//
// 判定できていないカテゴリは [diff.Summary.CanJudge] が false になる。そのときは
// 「0 件」ではなく [diff.Summary.JudgeBlockReason] の理由を出す。0 件と書くと
// 「移すべき訳は無い」と読まれ、翻訳者は訳を捨てる。
//
// 行の並びと見出しも同じ考え方で、internal/edit が読んだ物理行をそのまま出す。
// 見出しは internal/order から組み直さず、ファイルにある `# ===== ... =====` と
// `# --- ... ---` のコメント行を写す。画面は常にファイルの写しになる。
//
// # 待ち受けの絞り方
//
// 手元の1人が使う道具なので、外から届く経路を全部塞ぐ。
//
//   - 束ねる先は常に 127.0.0.1 に固定する。--port を指定しても変わらない。
//   - 起動のたびに32バイトのトークンを作り、最初の GET /?t=<トークン> でだけ
//     受け取る。以後は HttpOnly・SameSite=Strict の Cookie で持つ。
//   - Cookie が無い要求には 404 を返す。401 だと「そこに何かがある」と教えてしまう。
//   - Host ヘッダーを完全一致で検査する（DNS リバインディングへの対策）。
//   - Sec-Fetch-Site があれば同一生成元だけを通す。CORS のヘッダーは1つも返さない。
//   - 操作が絶えたら自分で終わる。翻訳者の PC に待ち受けを残さない。
