// Package publish は公開用の Translations/<ロケール>/strings.csv を組み立てる。
//
// 元実装は tools/hash-strings.ps1 で、ゲーム内Modの「Hash for commit」ボタンと
// 同じ出力を作る。翻訳者は手元で source_en 付きの作業コピーを編集し、コミット前に
// これを通す。公開ファイルは英語原文を持たず、各行は原文のハッシュ（internal/key）で
// 引かれる。
//
// # 入力をどこから取るか
//
// 入力はリポジトリの中だけから取る（[DiscoverTargets]）。Translations/_discovered に
// 作業コピーがあればそれ、無ければ公開ファイル自身である。出力は常に
// Translations/<ロケール>/strings.csv で、入力が公開ファイル自身のときこの処理は
// 冪等になる（同じバイト列が返る）。
//
// # publish はゲームのフォルダーを読まない
//
// [DiscoverEditTargets] はゲーム側の作業コピーも探すが、それを publish の入力に
// してはいけない。publish は入力から公開ファイルを作り直す処理なので、入力に無い行と
// 訳が空の行は、コミット済みの公開ファイルから消える。
//
// 実測（この開発機で、実機の ja.working.csv 1979行を入力に据えて publish を通した。
// 元の Translations/ja/strings.csv は 191,642 バイト・1721行）:
//
//	入力にした作業コピー                     ja/strings.csv      終了コード
//	途中まで（1979行のうち400行）            191,642 → 38,753    0
//	ヘッダーの引用符が閉じていない           191,642 →     43    0
//
// どちらも終了コードは 0 である。後者はヘッダーの source_en と translation が
// 1つの列名に融合し、translation 列が引けなくなる。全1712行が「訳が空」と見なされて
// 落ち、残ったのはヘッダー1行だけだった。壊れた入力ほど静かに消すので、
// 「失敗したら気づける」という受け止め方が成り立たない。
//
// 正常な作業コピーでも同じではない。実機の ja.working.csv をそのまま入力にすると、
// 行は1721行のまま消えないが、speaker 列が17行変わり（Ryan / Conrad → UI）、
// UI 行が10行入れ替わった。作業コピーは再生順に無い行の speaker を持たないためである。
//
// ゲーム側の作業コピーの訳をコミットする側へ入れるのは dwloc edit --game の仕事で、
// あちらは保存のたびに公開ファイルの「その行」だけを差し替える（internal/web の
// doc.go）。作り直しではないので、入力に無い行は消えない。
//
// 再生順（[LoadOrder]）も常にリポジトリ側から読む。ゲーム側の
// Translations/_discovered/script_order.csv は書き出したてで git に入っていないため、
// そちらを使うと dwloc diff の引き継ぎ候補が成り立たない。引き継ぎ候補は「git の
// 履歴から1つ前の再生順を読む」ことが根拠なので、履歴の無いファイルに替えると
// 判定そのものが消える。
//
// 組み立ての流れ（移植仕様「公開CSV生成」R11〜R27）:
//
//	(1) 入力CSVを1回走査して、キーごとの訳と台詞IDごとの訳を集める（[Build] 内の collect）
//	(2) 固定ヘッダーを書き、既存の公開ファイルからヘッダー直下のコメントを写す（R22/R23）
//	(3) script_order.csv のファイル順に走査し、訳のある行だけを見出し付きで書く（R24）
//	(4) 再生順に無かったキーを UI 見出しの下に、入力での登場順で書く（R25）
//	(5) 再生順に置けなかった台詞ID行を最後に書く（R26）
//
// 出力は BOM なし UTF-8、改行は常に LF（csvfile.LineTerminator のコメント参照）。
// 元実装の出力ファイルを入力として通すと、同じバイト列が返る（冪等）。
//
// このパッケージが元実装の癖を意図して再現している箇所:
//
//   - 見出しの再出力は「直前に出力した行」との比較で決める。過去に出したかは見ない
//     （移植仕様「敵対検証」[high] R24）。実データに同一セクション内のノード再訪が
//     2件あり、seen 集合で実装すると全ロケールで2行ずれる。
//   - key 列と order 列はCSVエスケープを通さず素のまま連結する（R24f）。
//   - 訳が空の行は出力しない。重複キーは先勝ちだが、空の訳はスロットを取らない
//     （R18/R20）。
//   - 引用フィールド内の改行はサポートしない。入力は1物理行=1レコードで読む
//     （移植仕様「敵対検証」[medium] R4、csvfile.ReadPowerShellRows）。
