// Package publish は公開用の Translations/<ロケール>/strings.csv を組み立てる。
//
// 元実装は tools/hash-strings.ps1 で、ゲーム内Modの「Hash for commit」ボタンと
// 同じ出力を作る。翻訳者は手元で source_en 付きの作業コピーを編集し、コミット前に
// これを通す。公開ファイルは英語原文を持たず、各行は原文のハッシュ（internal/key）で
// 引かれる。
//
// # 入力をどこから取るか
//
// 入力は作業コピーがあればそれ、無ければ公開ファイル自身である。作業コピーは
// リポジトリの Translations/_discovered を先に見て、ゲームのフォルダーを渡されて
// いればそちらも見る（[DiscoverTargetsWithGame]）。出力は常に
// Translations/<ロケール>/strings.csv で、入力が公開ファイル自身のときこの処理は
// 冪等になる（同じバイト列が返る。実機の13ロケールで確かめてある）。
//
// # publish はゲームのフォルダーを読む
//
// 以前はこの逆で、publish にはゲームのフォルダーを渡させない作りにしていた。
// それは誤りだった。理由はこの1行に尽きる。
//
//	publish は訳が空の行を公開ファイルに書かない（R20）。
//	したがって「未翻訳の行」と「公開ファイルに存在しない行」は同じ集合である。
//
// 実測（この開発機、実機のファイル）: ja.working.csv のデータ行は1958行、うち訳が
// 入っているキーは1721件、訳が空のキーは32件。Translations/ja/strings.csv の
// データ行はちょうど1721行で、訳の入った1721件と過不足なく一致した。訳が空の32件は
// 公開ファイルに1行も無い。
//
// だから、ゲームで入れた新しい訳をキーで公開ファイルへ書き戻すことはできない。
// 書き戻す先の行がそもそも無いからである。publish がゲーム側の作業コピーを読まない
// かぎり、翻訳者がいちばんやりたいこと——未訳の行を訳す——は、コミットする側へ
// 1行も届かない。
//
// # 危ないのは「読むこと」ではなく「訳が消えること」
//
// publish は入力から作り直す処理なので、入力が途中までだったり壊れていたりすると、
// コミット済みの訳がその場で消える。そこで、書き出す直前に [CheckLoss] を置いた。
// いまの公開ファイルに入っている訳が新しい出力に残らないなら、どのロケールも
// 1バイトも書かずに止まる。
//
// 実測（この開発機。実機の複写に対して、実機の ja.working.csv を入力に据えた。
// 元の Translations/ja/strings.csv は 191,642 バイト・データ行1721行）:
//
//	入力にした作業コピー                    失われる訳   書き出し   終了コード
//	途中まで（1958行のうち400行）           1,367 件     無し       1
//	ヘッダーの引用符が閉じていない          1,721 件     無し       1
//	公開ファイルにある行の訳を1つ空にした       1 件     無し       1
//	そのまま（未訳の行を1つ訳した）             0 件     有り       0
//
// 2つ目はヘッダーの source_en と translation が1つの列名に融合し、translation 列を
// 引けなくなる壊れ方である。全行が「訳が空」と見なされて落ちる。守りを入れる前は
// これが終了コード 0 で通り、公開ファイルがヘッダー1行だけになっていた。
// 壊れた入力ほど静かに消すので、「失敗したら気づける」が成り立たない。
//
// 4つ目では ja/strings.csv が 191,642 → 191,681 バイトになり、訳を入れた行が
// 1行増えた。ほかの12ロケール（作業コピーの無いロケール）は1バイトも変わらない。
//
// # 守るのは訳だけである
//
// [CheckLoss] が見るのは「訳が失われるか」だけで、ほかの列は見ない。実測では、
// 正常な作業コピーを入力にすると speaker 列が17行変わり（Ryan / Conrad → UI）、
// UI 見出しの下の10行が並び替わった。作業コピーは再生順に無い行の speaker を
// 持たないためで、訳は1つも失われていない。守りはここを止めない。
//
// # 再生順は常にリポジトリ側
//
// 再生順（[LoadOrder]）はゲームのフォルダーを渡されても常にリポジトリ側から読む。
// ゲーム側の Translations/_discovered/script_order.csv は書き出したてで git に
// 入っていないため、そちらを使うと dwloc diff の引き継ぎ候補が成り立たない。
// 引き継ぎ候補は「git の履歴から1つ前の再生順を読む」ことが根拠なので、履歴の
// 無いファイルに替えると判定そのものが消える。
//
// 組み立ての流れ（移植仕様「公開CSV生成」R11〜R27）:
//
//	(1) 入力CSVを1回走査して、キーごとの訳と台詞IDごとの訳を集める（[Build] 内の collect）
//	(2) 固定ヘッダーを書き、既存の公開ファイルからヘッダー直下のコメントを写す（R22/R23）
//	(3) script_order.csv のファイル順に走査し、訳のある行だけを見出し付きで書く（R24）
//	(4) 再生順に無かったキーを UI 見出しの下に、入力での登場順で書く（R25）
//	(5) 再生順に置けなかった台詞ID行を最後に書く（R26）
//
// 出力は BOM なし UTF-8、改行は常に LF（csvfile.LineTerminator のコメント参照）。
// 元実装の出力ファイルを入力として通すと、同じバイト列が返る（冪等）。
//
// このパッケージが元実装の癖を意図して再現している箇所:
//
//   - 見出しの再出力は「直前に出力した行」との比較で決める。過去に出したかは見ない
//     （移植仕様「敵対検証」[high] R24）。実データに同一セクション内のノード再訪が
//     2件あり、seen 集合で実装すると全ロケールで2行ずれる。
//   - key 列と order 列はCSVエスケープを通さず素のまま連結する（R24f）。
//   - 訳が空の行は出力しない。重複キーは先勝ちだが、空の訳はスロットを取らない
//     （R18/R20）。
//   - 引用フィールド内の改行はサポートしない。入力は1物理行=1レコードで読む
//     （移植仕様「敵対検証」[medium] R4、csvfile.ReadPowerShellRows）。
