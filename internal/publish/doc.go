// Package publish は公開用の Translations/<ロケール>/strings.csv を組み立てる。
//
// 元実装は tools/hash-strings.ps1 で、ゲーム内Modの「Hash for commit」ボタンと
// 同じ出力を作る。翻訳者は手元で source_en 付きの作業コピーを編集し、コミット前に
// これを通す。公開ファイルは英語原文を持たず、各行は原文のハッシュ（internal/key）で
// 引かれる。
//
// 組み立ての流れ（移植仕様「公開CSV生成」R11〜R27）:
//
//	(1) 入力CSVを1回走査して、キーごとの訳と台詞IDごとの訳を集める（[Build] 内の collect）
//	(2) 固定ヘッダーを書き、既存の公開ファイルからヘッダー直下のコメントを写す（R22/R23）
//	(3) script_order.csv のファイル順に走査し、訳のある行だけを見出し付きで書く（R24）
//	(4) 再生順に無かったキーを UI 見出しの下に、入力での登場順で書く（R25）
//	(5) 再生順に置けなかった台詞ID行を最後に書く（R26）
//
// 出力は BOM なし UTF-8、改行は常に LF（csvfile.LineTerminator のコメント参照）。
// 元実装の出力ファイルを入力として通すと、同じバイト列が返る（冪等）。
//
// このパッケージが元実装の癖を意図して再現している箇所:
//
//   - 見出しの再出力は「直前に出力した行」との比較で決める。過去に出したかは見ない
//     （移植仕様「敵対検証」[high] R24）。実データに同一セクション内のノード再訪が
//     2件あり、seen 集合で実装すると全ロケールで2行ずれる。
//   - key 列と order 列はCSVエスケープを通さず素のまま連結する（R24f）。
//   - 訳が空の行は出力しない。重複キーは先勝ちだが、空の訳はスロットを取らない
//     （R18/R20）。
//   - 引用フィールド内の改行はサポートしない。入力は1物理行=1レコードで読む
//     （移植仕様「敵対検証」[medium] R4、csvfile.ReadPowerShellRows）。
